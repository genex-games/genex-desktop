#!/usr/bin/env bash
# M0a.10a: measure what the Rust pond needs from the Mac game Seatbelt profile and write the rule
# proposal the owner decides on in M0a.10 (M1.13 then adds exactly the approved rules).
#
#   bash scripts/spike/rust-wgpu/seatbelt-measure.sh [--out <dir>] [--only pond-headless|pond-windowed]
#                                                    [--ticks N] [--frames N] [--no-raise]
#
# 1. Builds the pond (`pond --self-test`, the headless run) through rust-env.sh.
# 2. Generates and builds the window probe: the pond in a winit window, drawn by genex-render into
#    a wgpu surface on the window's CAMetalLayer and presented (the windowed run; no game has a
#    windowed Rust path yet, so the probe is the closest real one: genex-platform-desktop's shell,
#    genex-render's present, the pond's own frame). Its crate and its own target folder (no debug info,
#    about 1 GB, never the shared one) live in .studio-dev/seatbelt-measure/.
# 3. Runs seatbelt-measure.ts, which starts each program the way Studio starts a game under the
#    v1 profile of src/substrate/game-sandbox-profile.ts, reads the deny log, searches for the
#    smallest rule set that makes the run match its plain run, and writes deny-log/,
#    measurement.json and proposal.md to the output folder.
#
# Opens a window for a few seconds per windowed run, raised above the others (an occluded window
# gets no drawable); --no-raise leaves it where AppKit puts it, for an interactive check. Must run outside any other sandbox (the
# kernel does not report a nested profile's denials) on a Mac with a Metal GPU. Without a Metal
# device the plain run fails and the script refuses `reference-failed`; GENEX_REQUIRE_METAL=1 is
# accepted for symmetry with the test rows and changes nothing here: there is no skip.
# A refusal prints one typed line on stderr and exits 78:
#   seatbelt-measure-refusal: {"code":"<code>","detail":"<text>"}
# The default output is .studio-dev/evidence/m0a/seatbelt (the catalog's evidence folder).

set -euo pipefail

REFUSAL_EXIT=78
REPO="$(cd -P "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd -P)"
RUST_ENV="$REPO/scripts/spike/rust-wgpu/rust-env.sh"
WORKSPACE="$REPO/native/genex-rust"
WORK="$REPO/.studio-dev/seatbelt-measure"
PROBE_DIR="$WORK/window-probe"
PROBE_TARGET="$WORK/target"
OUT="$REPO/.studio-dev/evidence/m0a/seatbelt"
export CARGO_TARGET_DIR="${CARGO_TARGET_DIR:-$REPO/.studio-dev/cargo-target}"

refuse() {
  local detail=${2//\\/\\\\}
  detail=${detail//\"/\\\"}
  printf 'seatbelt-measure-refusal: {"code":"%s","detail":"%s"}\n' "$1" "$detail" >&2
  exit "$REFUSAL_EXIT"
}

[ "$(uname -s)" = "Darwin" ] || refuse not-darwin "Seatbelt is the Mac's"

PASS=()
while [ $# -gt 0 ]; do
  case $1 in
    --out)
      [ $# -ge 2 ] || refuse usage "--out needs a folder"
      OUT=$2
      shift 2
      ;;
    --only | --ticks | --frames)
      [ $# -ge 2 ] || refuse usage "$1 needs a value"
      PASS+=("$1" "$2")
      shift 2
      ;;
    --no-raise)
      PASS+=("$1")
      shift
      ;;
    *) refuse usage "unknown argument $1" ;;
  esac
done

# A version of a workspace dependency as Cargo.toml pins it (`name = { version = "=x" ...`).
workspace_version() {
  sed -n "s/^$1 = { version = \"\\([^\"]*\\)\".*/\\1/p" "$WORKSPACE/Cargo.toml" | head -n 1
}

write_probe() {
  local wgpu_version pollster_version
  wgpu_version=$(workspace_version wgpu)
  pollster_version=$(sed -n 's/^pollster = "\([^"]*\)".*/\1/p' "$WORKSPACE/Cargo.toml" | head -n 1)
  [ -n "$wgpu_version" ] && [ -n "$pollster_version" ] || refuse probe-failed "cannot read the wgpu and pollster pins"
  mkdir -p "$PROBE_DIR"
  # The workspace's own lock, so the probe resolves to the same vendored versions offline.
  cp "$WORKSPACE/Cargo.lock" "$PROBE_DIR/Cargo.lock"
  cat >"$PROBE_DIR/Cargo.toml" <<EOF
# Generated by scripts/spike/rust-wgpu/seatbelt-measure.sh (M0a.10a); not a workspace member.
[package]
name = "seatbelt-window-probe"
version = "0.0.0"
edition = "2024"
publish = false

[workspace]

[[bin]]
name = "seatbelt-window-probe"
path = "main.rs"

[dependencies]
genex = { path = "$WORKSPACE/crates/genex" }
genex-render = { path = "$WORKSPACE/crates/genex-render" }
genex-platform-desktop = { path = "$WORKSPACE/crates/genex-platform-desktop" }
genex-platform-web = { path = "$WORKSPACE/crates/genex-platform-web" }
pond = { path = "$WORKSPACE/examples/pond" }
pollster = "$pollster_version"
wgpu = { version = "$wgpu_version", default-features = false, features = ["std", "parking_lot", "metal", "wgsl"] }
raw-window-handle = "0.6.2"
objc2 = "0.6.5"
EOF
  cat >"$PROBE_DIR/main.rs" <<'EOF'
//! Seatbelt measurement probe (M0a.10a): the pond in a winit window, drawn by genex-render into a
//! wgpu surface on the window's CAMetalLayer and presented, for `--frames N` frames. Prints one
//! JSON line: surfaces created, frames presented, frames the surface gave no texture for, the first
//! error (null when none). `--no-raise` leaves the window where AppKit put it (the check that
//! raising it is not what a measured rule is for).

use genex::Runtime;
use genex_platform_desktop::{FrameControl, ShellFrame, ShellGame, ShellMode, ShellSurface, run};
use genex_platform_web::{GameHandle, MeshCache, to_scene};
use genex_render::{CullPath, Gpu, Renderer};
use objc2::runtime::AnyObject;
use raw_window_handle::{HasWindowHandle, RawWindowHandle};

const DEFAULT_FRAMES: u64 = 90;
/// `NSFloatingWindowLevel`: above ordinary windows, so the window is visible (an occluded window
/// gets no drawable from wgpu, and the present path would go unmeasured).
const FLOATING_WINDOW_LEVEL: isize = 3;

/// Raises the window above the others without activating the app (a background process cannot
/// take focus): the measured run must reach the CAMetalLayer present path.
fn raise(window: &ShellSurface) {
    let Ok(handle) = window.window_handle() else { return };
    let RawWindowHandle::AppKit(appkit) = handle.as_raw() else { return };
    let view = appkit.ns_view.as_ptr().cast::<AnyObject>();
    // SAFETY: `view` is the live NSView winit created for this window, used on the main thread.
    unsafe {
        let ns_window: *mut AnyObject = objc2::msg_send![view, window];
        if ns_window.is_null() {
            return;
        }
        let _: () = objc2::msg_send![ns_window, setLevel: FLOATING_WINDOW_LEVEL];
        let _: () = objc2::msg_send![ns_window, orderFrontRegardless];
    }
}

struct Drawn {
    surface: wgpu::Surface<'static>,
    config: wgpu::SurfaceConfiguration,
    gpu: Gpu,
    renderer: Renderer,
}

struct Probe {
    game: Box<dyn GameHandle>,
    meshes: MeshCache,
    drawn: Option<Drawn>,
    surfaces: u32,
    presented: u64,
    /// Frames the surface gave no texture for (occluded, timed out, outdated or lost).
    skipped: u64,
    error: Option<String>,
}

fn open(window: &ShellSurface) -> Result<Drawn, String> {
    let instance = genex_render::gpu::core_instance();
    let surface = instance.create_surface(window.clone()).map_err(|error| format!("create_surface: {error}"))?;
    let options = wgpu::RequestAdapterOptions {
        power_preference: wgpu::PowerPreference::HighPerformance,
        compatible_surface: Some(&surface),
        ..Default::default()
    };
    let adapter = pollster::block_on(instance.request_adapter(&options)).map_err(|error| format!("adapter: {error}"))?;
    let [width, height] = window.size();
    let config = surface
        .get_default_config(&adapter, width.max(1), height.max(1))
        .ok_or("the surface is not supported by the adapter")?;
    let gpu = pollster::block_on(Gpu::open(adapter)).map_err(|error| format!("device: {error}"))?;
    surface.configure(&gpu.device, &config);
    let [world_width, world_height] = pond_game::WORLD_SIZE;
    let renderer = Renderer::new(&gpu, world_width, world_height).map_err(|error| format!("renderer: {error}"))?;
    Ok(Drawn { surface, config, gpu, renderer })
}

impl Probe {
    fn draw(&mut self) -> Result<(), String> {
        let Some(drawn) = self.drawn.as_mut() else { return Ok(()) };
        let (frame, camera) = self.game.frame();
        let Drawn { surface, config, gpu, renderer } = drawn;
        self.meshes.load(&frame, pond_game::ASSETS, |mesh| renderer.add_mesh(gpu, mesh));
        renderer.render(gpu, &to_scene(&frame, &camera, &self.meshes), CullPath::Gpu).map_err(|error| error.to_string())?;
        let texture = match surface.get_current_texture() {
            wgpu::CurrentSurfaceTexture::Success(texture) | wgpu::CurrentSurfaceTexture::Suboptimal(texture) => texture,
            _ => {
                self.skipped += 1;
                return Ok(());
            }
        };
        let view = texture.texture.create_view(&wgpu::TextureViewDescriptor::default());
        renderer.present(gpu, &view, config.format, (config.width, config.height));
        gpu.queue.present(texture);
        self.presented += 1;
        Ok(())
    }
}

impl ShellGame for Probe {
    fn title(&self) -> String {
        "genex seatbelt window probe".to_owned()
    }

    fn world_size(&self) -> [u32; 2] {
        pond_game::WORLD_SIZE
    }

    fn surface_created(&mut self, surface: &ShellSurface) {
        self.surfaces += 1;
        if !std::env::args().any(|arg| arg == "--no-raise") {
            raise(surface);
        }
        match open(surface) {
            Ok(drawn) => self.drawn = Some(drawn),
            Err(error) => self.error = self.error.take().or(Some(error)),
        }
    }

    fn surface_resized(&mut self, size: [u32; 2], _scale: f64) {
        if let Some(drawn) = self.drawn.as_mut() {
            drawn.config.width = size[0].max(1);
            drawn.config.height = size[1].max(1);
            drawn.surface.configure(&drawn.gpu.device, &drawn.config);
        }
    }

    fn surface_lost(&mut self) {
        self.drawn = None;
    }

    fn frame(&mut self, frame: ShellFrame) -> FrameControl {
        self.game.advance_live(frame.frame_ms);
        if !frame.present {
            return FrameControl::Continue;
        }
        if let Err(error) = self.draw() {
            self.error = self.error.take().or(Some(error));
            return FrameControl::Exit;
        }
        FrameControl::Continue
    }
}

fn frames_arg() -> u64 {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let at = args.iter().position(|arg| arg == "--frames");
    at.and_then(|at| args.get(at + 1)).and_then(|value| value.parse().ok()).unwrap_or(DEFAULT_FRAMES)
}

fn main() {
    let mut game: Box<dyn GameHandle> = match Runtime::new(pond_game::game()) {
        Ok(runtime) => Box::new(runtime),
        Err(error) => {
            println!("{}", genex::json!({ "surfaces": 0, "presented": 0, "error": error.to_string() }));
            std::process::exit(1);
        }
    };
    game.start();
    let probe = Probe { game, meshes: MeshCache::default(), drawn: None, surfaces: 0, presented: 0, skipped: 0, error: None };
    let (probe, error) = match run(probe, ShellMode::Windowed, Some(frames_arg())) {
        Ok((probe, _exit)) => (Some(probe), None),
        Err(error) => (None, Some(error.to_string())),
    };
    let (surfaces, presented, skipped, error) = match probe {
        Some(probe) => (probe.surfaces, probe.presented, probe.skipped, probe.error),
        None => (0, 0, 0, error),
    };
    println!("{}", genex::json!({ "surfaces": surfaces, "presented": presented, "skipped": skipped, "error": error }));
    std::process::exit(if error.is_none() && presented > 0 { 0 } else { 1 });
}
EOF
}

echo "seatbelt-measure: building the pond" >&2
bash "$RUST_ENV" cargo build -p pond --offline --locked >&2 || refuse build-failed "cargo build -p pond failed"
# Copied out at once: the shared target is cleaned by other work while the measurement runs.
mkdir -p "$WORK/bin"
cp "$CARGO_TARGET_DIR/debug/pond" "$WORK/bin/pond" || refuse build-failed "no pond binary after the build"
POND="$WORK/bin/pond"

echo "seatbelt-measure: building the window probe" >&2
write_probe
# Its own target folder: the pond library is a cdylib, whose rlib has no hash in its file name, so
# a second workspace building it into the shared target would overwrite the workspace's copy.
GENEX_SPIKE_WORKSPACE="$PROBE_DIR" CARGO_TARGET_DIR="$PROBE_TARGET" CARGO_PROFILE_DEV_DEBUG=0 bash "$RUST_ENV" cargo build --offline >&2 ||
  refuse probe-failed "cargo build of the window probe failed"
PROBE="$PROBE_TARGET/debug/seatbelt-window-probe"

# shellcheck disable=SC1091 # nvm is the person's, when present
[ -s "${NVM_DIR:-$HOME/.nvm}/nvm.sh" ] && . "${NVM_DIR:-$HOME/.nvm}/nvm.sh" >/dev/null && nvm use 24 >/dev/null
node "$REPO/scripts/spike/rust-wgpu/seatbelt-measure.ts" --pond "$POND" --window-probe "$PROBE" --out "$OUT" ${PASS[@]+"${PASS[@]}"}
