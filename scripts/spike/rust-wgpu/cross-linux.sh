#!/usr/bin/env bash
# M0a spike only (M4.2 promotes it into the zig lane): cross-build the pond and the desktop shell
# for x86_64-unknown-linux-gnu.2.28 from the Mac with zig 0.16.0 + cargo-zigbuild 0.23.4 (Q7:
# Linux targets only, never Apple targets).
#
#   bash scripts/spike/rust-wgpu/cross-linux.sh [--no-sysroot]
#
# cpal links libasound (alsa-sys) and gilrs-core links libudev (libudev-sys); both find their
# library through pkg-config. The Mac has neither, so the script first writes the extended
# sysroot under .studio-dev/cross/linux-sysroot-2.28:
#   - usr/lib64/libasound.so.2 and libudev.so.1: link stubs built by zig for glibc 2.28, one empty
#     function per symbol alsa-sys 0.4.0 / libudev-sys 0.1.4 declare (their bindings are
#     pre-generated, so no headers are needed), with the real SONAMEs; the unversioned
#     references bind to each library's default symbol version at run time;
#   - usr/lib64/pkgconfig/alsa.pc and libudev.pc;
#   - bin/pkg-config: a small pkg-config for those .pc files (the Mac has no pkg-config).
# The build sets the target-scoped PKG_CONFIG, PKG_CONFIG_PATH, PKG_CONFIG_SYSROOT_DIR and
# PKG_CONFIG_ALLOW_CROSS (plan: "lane sets PKG_CONFIG_SYSROOT_DIR/PATH/ALLOW_CROSS").
#
# It also builds scripts/spike/rust-wgpu/link-probe, which calls cpal and gilrs, and
# requires its DT_NEEDED to name libasound.so.2 and libudev.so.1.
#
# Checks on every ELF file: x86-64, every GLIBC_ symbol version <= 2.28, DT_NEEDED within the
# plan's allow-list. `--no-sysroot` is the red row: the same build without the sysroot must fail
# in a pkg-config build script (exit 0 when it fails that way, 1 otherwise).
#
# The plan's AlmaLinux 8.10 bundle is not downloaded in this run (not an authorized source):
# zig's own glibc 2.28 stubs stand in for it.

set -euo pipefail
# shellcheck source=cross-lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/cross-lib.sh"
CROSS_NAME=cross-linux

LINUX_TARGET="x86_64-unknown-linux-gnu.2.28"
LINUX_TRIPLE="x86_64-unknown-linux-gnu"
LINUX_TRIPLE_ENV="x86_64_unknown_linux_gnu"
LINUX_GLIBC_MAX="2.28"
LINUX_SYSROOT="$CROSS_WORK/linux-sysroot-2.28"
VENDOR="$CROSS_SPIKE_DIR/vendor"
ALSA_SYS="$VENDOR/alsa-sys-0.4.0"
UDEV_SYS="$VENDOR/libudev-sys-0.1.4"
LINK_PROBE="$CROSS_REPO/scripts/spike/rust-wgpu/link-probe"
# Plan "Sandbox, admission and export per destination", Linux row (plus glibc's own split libs).
LINUX_NEEDED_ALLOWED=" libc.so.6 libm.so.6 libdl.so.2 libpthread.so.0 librt.so.1 ld-linux-x86-64.so.2 libgcc_s.so.1 libasound.so.2 libudev.so.1 "

zig_bin() {
  set -e
  local zig="$CROSS_SPIKE_DIR/tools/zig/zig"
  [ -x "$zig" ] || cross_fail tool-missing "zig is not installed at $zig (setup-toolchain.sh --with zig)"
  printf '%s\n' "$zig"
}

# The stub's C source: one empty function per `pub fn <prefix>…` the binding crate declares.
stub_source() {
  set -e
  local crate=$1 prefix=$2
  [ -d "$crate/src" ] || cross_fail vendor-missing "$crate is not vendored"
  printf '/* Link stub generated by cross-linux.sh from %s. Never executed. */\n' "$(basename "$crate")"
  grep -ohE "pub fn ${prefix}[A-Za-z0-9_]+" "$crate"/src/*.rs | sed 's/^pub fn //' | sort -u |
    while IFS= read -r symbol; do printf 'void %s(void) {}\n' "$symbol"; done
}

# stub_library <crate> <prefix> <soname> <link name>
stub_library() {
  set -e
  local crate=$1 prefix=$2 soname=$3 link=$4 lib="$LINUX_SYSROOT/usr/lib64" src
  src="$CROSS_WORK/linux-stub-$link.c"
  stub_source "$crate" "$prefix" >"$src"
  "$(zig_bin)" cc -target x86_64-linux-gnu.2.28 -shared -fPIC -nostdlib -O0 \
    "-Wl,-soname,$soname" -o "$lib/$soname" "$src"
  ln -sf "$soname" "$lib/lib$link.so"
  grep -c '^void ' "$src"
}

write_pc() {
  set -e
  local name=$1 version=$2 link=$3
  cat >"$LINUX_SYSROOT/usr/lib64/pkgconfig/$name.pc" <<EOF
prefix=/usr
libdir=\${prefix}/lib64
includedir=\${prefix}/include

Name: $name
Description: link stub for the genex Linux cross sysroot
Version: $version
Libs: -L\${libdir} -l$link
Cflags: -I\${includedir}
EOF
}

# A pkg-config that answers --exists, --modversion, --libs and --cflags from the .pc files on
# PKG_CONFIG_PATH, prefixing -L/-I paths with PKG_CONFIG_SYSROOT_DIR like the real one.
write_pkg_config() {
  set -e
  cat >"$LINUX_SYSROOT/bin/pkg-config" <<'EOF'
#!/usr/bin/env bash
# Generated by cross-linux.sh: the subset of pkg-config the pkg-config crate uses.
set -euo pipefail
want_libs=0 want_cflags=0 want_version=0 modules=""
for arg in "$@"; do
  case $arg in
    --libs) want_libs=1 ;;
    --cflags) want_cflags=1 ;;
    --modversion) want_version=1 ;;
    --version) echo 0.29.2; exit 0 ;;
    --*) ;;
    *) modules="$modules $arg" ;;
  esac
done
find_pc() {
  set -e
  local dir old_ifs=$IFS
  IFS=:
  for dir in ${PKG_CONFIG_PATH:-}; do
    if [ -f "$dir/$1.pc" ]; then IFS=$old_ifs; printf '%s\n' "$dir/$1.pc"; return 0; fi
  done
  IFS=$old_ifs
  return 1
}
field() {
  set -e
  awk -v key="$2" -v sysroot="${PKG_CONFIG_SYSROOT_DIR:-}" '
    /^[A-Za-z_]+=/ { split($0, kv, "="); name = kv[1]; value = substr($0, length(name) + 2)
      for (v in vars) gsub("\\$\\{" v "\\}", vars[v], value); vars[name] = value; next }
    index($0, key ": ") == 1 { value = substr($0, length(key) + 3)
      for (v in vars) gsub("\\$\\{" v "\\}", vars[v], value)
      n = split(value, word, " "); out = ""
      for (i = 1; i <= n; i++) { w = word[i]
        if (sysroot != "" && (w ~ /^-L\// || w ~ /^-I\//)) w = substr(w, 1, 2) sysroot substr(w, 3)
        out = out (out == "" ? "" : " ") w }
      print out }' "$1"
}
out=""
for module in $modules; do
  pc=$(find_pc "$module") || { echo "Package $module was not found in the pkg-config search path." >&2; exit 1; }
  [ "$want_version" = 1 ] && field "$pc" Version
  [ "$want_cflags" = 1 ] && out="$out $(field "$pc" Cflags)"
  [ "$want_libs" = 1 ] && out="$out $(field "$pc" Libs)"
done
[ -n "${out// /}" ] && echo "${out# }"
exit 0
EOF
  chmod +x "$LINUX_SYSROOT/bin/pkg-config"
}

prepare_sysroot() {
  set -e
  local stamp="$LINUX_SYSROOT/manifest.json" alsa_count udev_count
  rm -rf "$LINUX_SYSROOT"
  mkdir -p "$LINUX_SYSROOT/usr/lib64/pkgconfig" "$LINUX_SYSROOT/usr/include" "$LINUX_SYSROOT/bin"
  alsa_count=$(stub_library "$ALSA_SYS" snd_ libasound.so.2 asound)
  udev_count=$(stub_library "$UDEV_SYS" udev_ libudev.so.1 udev)
  write_pc alsa 1.2.10 asound
  write_pc libudev 239 udev
  write_pkg_config
  printf '{"format":"genex-linux-cross-sysroot/1","glibc":"%s","stubs":{"libasound.so.2":{"from":"alsa-sys-0.4.0","symbols":%s},"libudev.so.1":{"from":"libudev-sys-0.1.4","symbols":%s}},"headers":false,"almaLinuxBundle":false}\n' \
    "$LINUX_GLIBC_MAX" "$alsa_count" "$udev_count" >"$stamp"
  cross_log "sysroot ready: $alsa_count libasound and $udev_count libudev stub symbols"
}

export_sysroot_env() {
  set -e
  export "PKG_CONFIG_$LINUX_TRIPLE_ENV=$LINUX_SYSROOT/bin/pkg-config"
  export "PKG_CONFIG_PATH_$LINUX_TRIPLE_ENV=$LINUX_SYSROOT/usr/lib64/pkgconfig"
  export "PKG_CONFIG_SYSROOT_DIR_$LINUX_TRIPLE_ENV=$LINUX_SYSROOT"
  export "PKG_CONFIG_ALLOW_CROSS_$LINUX_TRIPLE_ENV=1"
}

zigbuild_args() {
  set -e
  printf '%s\n' zigbuild -p pond -p genex-platform-desktop --bin pond --bin genex-desktop-spike --no-default-features \
    --release --target "$LINUX_TARGET" --offline --locked
}

# The red row: without the sysroot a pkg-config build script must fail the build.
red_without_sysroot() {
  set -e
  local log="$CROSS_EVIDENCE/linux-no-sysroot.log" status=0 args=()
  local line
  while IFS= read -r line; do args+=("$line"); done < <(zigbuild_args)
  mkdir -p "$CROSS_EVIDENCE"
  bash "$CROSS_RUST_ENV" cargo "${args[@]}" >"$log" 2>&1 || status=$?
  if [ "$status" -ne 0 ] && grep -E -q "alsa-sys|libudev-sys" "$log" && grep -E -q -i "pkg-config|pkg_config" "$log"; then
    cross_log "red as expected: the build fails in a pkg-config build script without the sysroot ($log)"
    return 0
  fi
  cross_fail red-row-passed "the build without the sysroot exited $status without a pkg-config failure ($log)"
}

glibc_max() {
  set -e
  "$(cross_tool llvm-objdump)" -T "$1" | grep -oE 'GLIBC_[0-9]+(\.[0-9]+)*' | sed 's/GLIBC_//' | sort -t. -k1,1n -k2,2n -k3,3n | tail -1
}

version_le() {
  set -e
  [ "$(printf '%s\n%s\n' "$1" "$2" | sort -t. -k1,1n -k2,2n -k3,3n | head -1)" = "$1" ]
}

needed_libs() {
  set -e
  "$(cross_tool llvm-readobj)" --needed-libs "$1" | awk '/^  [^ ]/ { gsub(/^ +| +$/, ""); print }' | grep -v '^NeededLibraries' || true
}

check_elf() {
  set -e
  local file=$1 header max lib needed
  header=$("$(cross_tool llvm-readobj)" --file-headers "$file")
  printf '%s\n' "$header" | grep -q 'Machine: EM_X86_64' || cross_fail wrong-machine "$file is not an x86-64 ELF"
  max=$(glibc_max "$file")
  [ -n "$max" ] || cross_fail no-glibc-versions "$file references no GLIBC_ symbol versions"
  version_le "$max" "$LINUX_GLIBC_MAX" || cross_fail glibc-too-new "$file needs GLIBC_$max > $LINUX_GLIBC_MAX"
  needed=$(needed_libs "$file")
  for lib in $needed; do
    case $LINUX_NEEDED_ALLOWED in *" $lib "*) ;; *) cross_fail needed-not-allowed "$file needs $lib" ;; esac
  done
  printf '"glibcMax":"%s","needed":%s' "$max" "$(printf '%s\n' "$needed" | cross_json_lines)"
}

main() {
  set -e
  if [ "${1:-}" = --no-sysroot ]; then
    red_without_sysroot
    return 0
  fi
  [ $# -eq 0 ] || cross_fail usage "usage: cross-linux.sh [--no-sysroot]"
  cross_require_disk
  prepare_sysroot
  export_sysroot_env
  local log="$CROSS_EVIDENCE/linux-build.jsonl" ms args=() line pond spike
  while IFS= read -r line; do args+=("$line"); done < <(zigbuild_args)
  ms=$(cross_cargo "$log" "${args[@]}")
  pond=$(cross_artifact "$log" pond pond bin)
  pond=$(cross_keep "$pond" linux)
  spike=$(cross_artifact "$log" genex-platform-desktop genex-desktop-spike bin)
  spike=$(cross_keep "$spike" linux)
  # The runtime crates do not call cpal or gilrs yet, so --as-needed drops both libraries from
  # pond's DT_NEEDED: the probe calls them, and its ELF must need both.
  local probe_log="$CROSS_EVIDENCE/linux-link-probe.jsonl" probe_ms probe probe_needed
  probe_ms=$(GENEX_SPIKE_WORKSPACE="$LINK_PROBE" cross_cargo "$probe_log" zigbuild --release \
    --target "$LINUX_TARGET" --offline --locked)
  probe=$(cross_artifact "$probe_log" genex-link-probe genex-link-probe bin)
  probe=$(cross_keep "$probe" linux)
  probe_needed=$(needed_libs "$probe")
  for lib in libasound.so.2 libudev.so.1; do
    printf '%s\n' "$probe_needed" | grep -qx "$lib" || cross_fail link-probe-missing "$probe does not need $lib"
  done
  local pond_elf spike_elf probe_elf
  pond_elf=$(check_elf "$pond")
  spike_elf=$(check_elf "$spike")
  probe_elf=$(check_elf "$probe")
  cross_record linux.json "$(printf '{"format":"genex-cross/1","destination":"linux","target":"%s","toolchain":{"zig":"0.16.0","cargoZigbuild":"0.23.4"},"sysroot":%s,"artifacts":[{"name":"pond",%s,%s},{"name":"genex-desktop-spike",%s,%s},{"name":"link-probe",%s,%s}]}' \
    "$LINUX_TARGET" "$(cat "$LINUX_SYSROOT/manifest.json")" \
    "$(cross_artifact_json "$pond" "$ms")" "$pond_elf" \
    "$(cross_artifact_json "$spike" "$ms")" "$spike_elf" \
    "$(cross_artifact_json "$probe" "$probe_ms")" "$probe_elf")"
}

main "$@"
