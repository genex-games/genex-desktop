/**
 * The `@genex-ai/physics` glue as a factory (`scripts/physics-wasm.ts`, step 2): wasm-bindgen's
 * `--target web` glue keeps one instance in module state, so the package could hold one WebAssembly
 * instance per process. `factoryGlue` wraps the generated text, unchanged, in `createGlue()`: each
 * call is a glue of its own, with its own instance and caches, whose exports are the generated
 * module's (plus `__genex_module()`, the compiled `WebAssembly.Module` it instantiated). `core.js`
 * makes the package's own instance with one call and each `createBinding()` with another, from the
 * module compiled once.
 *
 * The transform refuses a glue of any other shape (an import, another export form, an export it
 * cannot name), so a wasm-bindgen upgrade that changes the shape fails the build, never the package.
 */

/** The one line wasm-bindgen 0.2.129 ends the glue with. */
const TRAILING_EXPORT = "export { initSync, __wbg_init as default };";
const EXPORTED_FUNCTION = /^export function ([A-Za-z_$][\w$]*)\s*\(/gm;
const ANY_EXPORT = /^export\b/m;
const ANY_IMPORT = /^import\b/m;
const HEADER = [
  "// Generated by wasm-bindgen 0.2.129 (--target web), wrapped by scripts/physics-wasm-glue.ts:",
  "// createGlue() is one glue of its own (its own WebAssembly instance and caches) per call.",
].join("\n");

/** The glue `text` wasm-bindgen wrote, as `export function createGlue()`; throws on any other shape. */
export function factoryGlue(text: string): string {
  if (ANY_IMPORT.test(text)) throw new Error("physics-wasm-glue: the glue imports a module");
  const lines = text.trimEnd().split("\n");
  if (lines.at(-1) !== TRAILING_EXPORT)
    throw new Error("physics-wasm-glue: the glue does not end with its init export");
  const body = lines.slice(0, -1).join("\n");
  const names = [...body.matchAll(EXPORTED_FUNCTION)].map((match) => match[1]);
  if (names.length === 0) throw new Error("physics-wasm-glue: the glue exports no function");
  const plain = body.replace(EXPORTED_FUNCTION, (_whole, name: string) => `function ${name}(`);
  if (ANY_EXPORT.test(plain)) throw new Error("physics-wasm-glue: the glue has an export of another form");
  const members = [...names, "initSync", "default: __wbg_init", "__genex_module: () => wasmModule"];
  return [
    HEADER,
    "export function createGlue() {",
    plain,
    `return Object.freeze({ __proto__: null, ${members.join(", ")} });`,
    "}",
    "",
  ].join("\n");
}
