/** The tool `name` from its option, else `fallback` under the toolchains; refused when missing. */
function pickTool(values: Record<string, string | boolean | undefined>, name: string, fallback: string): string {
  const given = values[name];
  const chosen = typeof given === "string" ? path.resolve(given) : path.join(toolchainsRoot(values), fallback);
  if (!existsSync(chosen)) throw new Error(MESSAGE.Missing(name, chosen));
  return chosen;
}

