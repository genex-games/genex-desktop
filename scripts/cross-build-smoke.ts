/**
 * A Linux sysroot shaped as the store's (a `manifest.json` pinning each file in the ANGLE
 * manifests' format), holding the Wayland protocol code the build compiled, which is what the
 * Linux export reads licences from. Written in place on every run; nothing is removed.
 */
async function exportSysroot(protocols: string, work: string): Promise<CrossAngle> {
  const dir = path.join(work, EXPORT_SYSROOT);
  await mkdir(path.join(dir, SYSROOT_PROTOCOLS), { recursive: true });
  const files: Record<string, { sha256: string; size: number }> = {};
  const names = (await readdir(protocols)).filter((name) => PROTOCOL_CODE.test(name)).sort();
  for (const name of names) {
    const bytes = await readFile(path.join(protocols, name));
    await writeFile(path.join(dir, SYSROOT_PROTOCOLS, name), bytes);
    files[`${SYSROOT_PROTOCOLS}/${name}`] = { sha256: sha256(bytes), size: bytes.length };
  }
  const manifest = `${JSON.stringify({ schema: 1, target: "linux-x64-sysroot", files }, null, 2)}\n`;
  await writeFile(path.join(dir, ANGLE_MANIFEST), manifest);
  return { dir, manifestSha256: sha256(manifest) };
}

