/** The Linux package run in a container with no network or on this host; returns its output folder and image. */
async function runLinux(pkg: Package, out: string, plan: RunPlan) {
  const { mode, kind, probe } = plan;
  await mkdir(out, { recursive: true });
  const log = path.join(out, "run.log");
  const script = kind.display === Display.Wayland ? WAYLAND_SCRIPT : X11_SCRIPT;
  if (mode === RunMode.Host) {
    const env = { GAME_DIR: pkg.root, GAME_EXE: pkg.exe, OUT_DIR: out, FB_DIR: path.join(out, "fb") };
    await exec("Linux run", "sh", ["-c", script], log, { ...env, ...probeEnv(kind, probe) });
    return { out, image: null };
  }
  const image = await runImage(kind, path.dirname(out), plan.fetch);
  const mounts = ["-v", `${pkg.root}:/game:ro`, "-v", `${out}:/out`, "-e", "GAME_DIR=/game", "-e", "OUT_DIR=/out"];
  // The framebuffer file is memory-mapped: it stays in the container's own /tmp, not the bind mount.
  mounts.push("-e", `GAME_EXE=${pkg.exe}`, "-e", "FB_DIR=/tmp/fb", "-v", `${probe}:/probe/studio-probe:ro`);
  for (const [name, value] of Object.entries(probeEnv(kind, "/probe/studio-probe")))
    mounts.push("-e", `${name}=${value}`);
  const shell = `${listCommand(kind)} || exit 97\n${script}`;
  const args = ["run", "--rm", "--network", "none", "--platform", PLATFORM, ...mounts, image.image, "sh", "-c", shell];
  await exec("Linux run", "docker", args, log);
  return { out, image };
}

/** The XWD header fields this reader needs. */
interface XwdHeader {
  headerSize: number;
  width: number;
  height: number;
  byteOrder: number;
  step: number;
  bytesPerLine: number;
  start: number;
}

/** A header whose fields do not describe a 24- or 32-bit screen that fits inside the file. */
function unreadableXwd(xwd: Buffer, header: XwdHeader): boolean {
  const { headerSize, width, height, step, bytesPerLine, start } = header;
  const pixelSize = step === 3 || step === 4;
  const sane = headerSize >= XWD_HEADER_BYTES && width > 0 && height > 0 && width * height <= MAX_SCREEN_PIXELS;
  const fits = bytesPerLine >= width * step && xwd.length >= start + bytesPerLine * height;
  return !(pixelSize && sane && fits);
}

/** An XWD dump's header, or null when the file is shorter than the fixed header. */
function xwdHeader(xwd: Buffer): XwdHeader | null {
  if (xwd.length < XWD_HEADER_BYTES) return null;
  const field = (index: number) => xwd.readUInt32BE(index * 4);
  const headerSize = field(0);
  return {
    headerSize,
    width: field(4),
    height: field(5),
    byteOrder: field(7),
    step: field(11) / 8,
    bytesPerLine: field(12),
    start: headerSize + field(19) * XWD_COLOUR_BYTES,
  };
}

/** `raw` RGB rows (each led by a filter byte) as a PNG. */
function png(raw: Buffer, width: number, height: number): Buffer {
  const chunk = (type: string, data: Buffer) => {
    const body = Buffer.concat([Buffer.from(type, "latin1"), data]);
    const length = Buffer.alloc(4);
    length.writeUInt32BE(data.length, 0);
    const crc = Buffer.alloc(4);
    crc.writeUInt32BE(zlib.crc32(body));
    return Buffer.concat([length, body, crc]);
  };
  const head = Buffer.alloc(13);
  head.writeUInt32BE(width, 0);
  head.writeUInt32BE(height, 4);
  head.set([8, 2, 0, 0, 0], 8);
  const signature = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]);
  return Buffer.concat([
    signature,
    chunk("IHDR", head),
    chunk("IDAT", zlib.deflateSync(raw)),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

/** An X window dump (24 or 32 bits per pixel) as a PNG, or null when its header does not describe the file. */
function xwdToPng(xwd: Buffer): { png: Buffer; width: number; height: number; colours: number } | null {
  const header = xwdHeader(xwd);
  if (header === null || unreadableXwd(xwd, header)) return null;
  const { width, height, byteOrder, step, bytesPerLine, start } = header;
  const row = width * 3 + 1;
  const raw = Buffer.alloc(row * height);
  const colours = new Set<number>();
  for (let y = 0; y < height; y++)
    for (let x = 0; x < width; x++) {
      const at = start + y * bytesPerLine + x * step;
      const pixel = byteOrder === 0 ? xwd.readUIntLE(at, 3) : xwd.readUIntBE(at + step - 3, 3);
      colours.add(pixel);
      raw.writeUIntBE(pixel, y * row + 1 + x * 3, 3);
    }
  return { png: png(raw, width, height), width, height, colours: colours.size };
}

/** A binary PPM (`P6`, 8 bits per channel) from grim as a PNG, or null when it is not one. */
function ppmToPng(ppm: Buffer): { png: Buffer; width: number; height: number; colours: number } | null {
  const header = /^P6\s+(\d+)\s+(\d+)\s+255\s/.exec(ppm.subarray(0, 64).toString("latin1"));
  if (!header) return null;
  const width = Number(header[1]);
  const height = Number(header[2]);
  const start = header[0].length;
  const fits = width > 0 && height > 0 && width * height <= MAX_SCREEN_PIXELS;
  if (!fits || ppm.length < start + width * height * 3) return null;
  const row = width * 3 + 1;
  const raw = Buffer.alloc(row * height);
  const colours = new Set<number>();
  for (let y = 0; y < height; y++) {
    const line = ppm.subarray(start + y * width * 3, start + (y + 1) * width * 3);
    line.copy(raw, y * row + 1);
    for (let x = 0; x < width; x++) colours.add(line.readUIntBE(x * 3, 3));
  }
  return { png: png(raw, width, height), width, height, colours: colours.size };
}

/** A file's bytes, empty when it was never written (a run that stopped early). */
async function readIfPresent(file: string): Promise<Buffer> {
  return existsSync(file) ? readFile(file) : Buffer.alloc(0);
}

/** The run's failures from what the game logged and which libraries the loader opened from its folder. */
function logFailures(kind: RunKind, gameLog: string, loaded: readonly string[], gameDir: string): string[] {
  const platform = GLFW_PLATFORM.exec(gameLog)?.[1] ?? "nothing";
  return [
    ...(VULKAN_SWIFTSHADER_RENDERER.test(gameLog) ? [] : [MESSAGE.NoRenderer]),
    ...(platform === kind.display ? [] : [MESSAGE.WrongPlatform(kind.display, platform)]),
    ...ANGLE_LINUX_LIBRARIES.filter((library) => !loaded.includes(path.posix.join(gameDir, library))).map(
      MESSAGE.NotBundled,
    ),
  ];
}

/** The run's screenshot (Xvfb's XWD or grim's PPM) as a PNG in the evidence folder, or null when unreadable. */
async function screenshot(out: string, kind: RunKind, evidence: string) {
  const shot =
    kind.display === Display.X11
      ? xwdToPng(await readIfPresent(path.join(out, "screen.xwd")))
      : ppmToPng(await readIfPresent(path.join(out, "screen.ppm")));
  if (shot) await writeFile(path.join(evidence, `${kind.name}.png`), shot.png);
  return shot;
}

/** An X11 run's studio-protocol verdicts and whether the probe passed (exit 0); null for a run without the probe. */
async function probeVerdicts(out: string, kind: RunKind): Promise<{ ok: boolean; verdicts: string[] } | null> {
  if (kind.display !== Display.X11) return null;
  const text = (await readIfPresent(path.join(out, "protocol"))).toString("utf8");
  const verdicts = text.split("\n").filter((line) => line !== "" && !line.startsWith("game> "));
  const exit = (await readIfPresent(path.join(out, "probe-exit"))).toString("utf8").trim();
  return { ok: exit === "0", verdicts };
}

/** The run's evidence: the screenshot (X11) as a PNG with its sha256, the log lines and the libraries loaded. */
async function runEvidence(out: string, kind: RunKind, gameDir: string, evidence: string) {
  const text = async (file: string) => (await readIfPresent(path.join(out, file))).toString("utf8");
  const state = (await text("state")).trim() || "no state";
  const shot = await screenshot(out, kind, evidence);
  const gameLog = await text("game.log");
  const trace = await text("ld-debug.log");
  // The Vulkan loader opens the ICD as `<folder>/./libvk_swiftshader.so`: compare normalised paths.
  const inits = [...trace.matchAll(/calling init: (\S+)/g)].map((match) => path.posix.normalize(match[1] ?? ""));
  const loaded = [...new Set(inits)].sort();
  for (const file of ["game.log", "ld-debug.log", "packages.txt", "server.log", "protocol"])
    if (existsSync(path.join(out, file))) await cp(path.join(out, file), path.join(evidence, `${kind.name}.${file}`));
  const colours = shot?.colours ?? 0;
  const blank = colours < MIN_COLOURS;
  const protocol = await probeVerdicts(out, kind);
  const failures = [
    ...(state === "alive" ? [] : [MESSAGE.Exited(state)]),
    ...(blank ? [MESSAGE.Blank(colours)] : []),
    ...logFailures(kind, gameLog, loaded, gameDir),
    ...(protocol === null || protocol.ok ? [] : [MESSAGE.Protocol(protocol.verdicts)]),
  ];
  const renderer = /> Renderer: (.*)$/m.exec(gameLog)?.[1] ?? null;
  const platform = GLFW_PLATFORM.exec(gameLog)?.[1] ?? null;
  const picture = {
    width: shot?.width ?? 0,
    height: shot?.height ?? 0,
    colours,
    pngSha256: shot ? sha256(shot.png) : null,
  };
  return { state, display: kind.display, renderer, platform, protocol, ...picture, loaded, failures };
}

type Options = ReturnType<typeof optionsFrom>;

/** The target an exported archive is for, from its file name. */
function archiveTarget(file: string): { target: CrossTarget; format: ArchiveFormat } {
  if (file.endsWith(".zip")) return { target: CrossTarget.WindowsX64, format: ArchiveFormat.Zip };
  if (file.endsWith(".tar.gz") || file.endsWith(".tgz"))
    return { target: CrossTarget.LinuxX64, format: ArchiveFormat.TarGz };
  throw new Error(MESSAGE.BadArchive(file));
}

function optionsFrom(values: Record<string, string | boolean | undefined>) {
  const targets = String(values.targets ?? Object.values(CrossTarget).join(","))
    .split(",")
    .map((value) => value.trim());
  for (const target of targets) if (!isCrossTarget(target)) throw new Error(MESSAGE.BadTarget(target));
  const run = String(values.run ?? RunMode.Docker);
  if (!Object.values<string>(RunMode).includes(run)) throw new Error(MESSAGE.BadRun(run));
  const fromArchive = typeof values["from-archive"] === "string" ? path.resolve(values["from-archive"]) : null;
  if (fromArchive !== null) archiveTarget(fromArchive);
  const modes = [fromArchive !== null, values.export === true, values.repro === true].filter(Boolean);
  if (modes.length > 1) throw new Error(MESSAGE.Modes);
  return {
    targets: targets as CrossTarget[],
    run: run as RunMode,
    floor: values.floor === true,
    wayland: values.wayland === true,
    fetch: values.fetch === true,
    export: values.export === true,
    repro: values.repro === true,
    allowPdbDifference: values["allow-pdb-difference"] === true,
    fromArchive,
  };
}

