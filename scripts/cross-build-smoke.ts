/** `found` refused unless it is exactly the pinned package list. */
function assertPinned(what: string, found: readonly string[], pinned: readonly string[]): void {
  const same = found.length === pinned.length && found.every((entry, index) => entry === pinned[index]);
  if (!same) throw new Error(MESSAGE.Unpinned(what, found, pinned));
}

/**
 * `script` run once in a throwaway floor container with `staging` mounted at /out (and `mounts`),
 * the package list it wrote checked against `pinned`, and the folder renamed into `target` with
 * its record: nothing half-written is ever left at `target`. The container installs packages, so
 * it is the one kind that has the network, and it runs only when `fetch` allows it.
 */
async function fetchOnce(
  target: string,
  script: string,
  pinned: readonly string[],
  logs: string,
  fetch: boolean,
  mounts: readonly string[] = [],
): Promise<Record<string, unknown>> {
  const recordPath = path.join(target, RECORD);
  if (existsSync(recordPath)) {
    const record = JSON.parse(await readFile(recordPath, "utf8")) as { packages: string[] };
    assertPinned(path.basename(target), record.packages, pinned);
    return record;
  }
  if (!fetch) throw new Error(MESSAGE.NeedsFetch(target));
  await mkdir(path.dirname(target), { recursive: true });
  const staging = await mkdtemp(`${target}.partial-`);
  const log = path.join(logs, `${path.basename(target)}-fetch.log`);
  const volumes = ["-v", `${staging}:/out`, ...mounts];
  await exec(
    "floor fetch",
    "docker",
    ["run", "--rm", "--platform", PLATFORM, ...volumes, FLOOR_IMAGE, "sh", "-c", script],
    log,
  );
  const packages = (await readFile(path.join(staging, "packages.txt"), "utf8")).trim().split("\n");
  assertPinned(path.basename(target), packages, pinned);
  const record = {
    image: FLOOR_IMAGE,
    platform: PLATFORM,
    fetchedAt: new Date().toISOString(),
    base: (await readFile(path.join(staging, "base.txt"), "utf8")).trim(),
    packages,
  };
  await writeFile(path.join(staging, RECORD), `${JSON.stringify(record, null, 2)}\n`);
  await rename(staging, target);
  return record;
}

