/**
 * Opt-in real cross-build of the C++ · raylib starter game for Windows x64 and Linux x64 with
 * zig, through `src/substrate/toolchain-store/cross-targets.ts`: prebuilds raylib 6.0 for each
 * target (desktop GLFW over ANGLE's GLES 3.0; X11 and Wayland on Linux), builds
 * `src/game-template-cpp` against it, checks the host-gate facts with `llvm-readobj` (Windows
 * imports `libGLESv2.dll` and never `opengl32.dll`; Linux needs `libGLESv2.so`, never `libGL`, has
 * a RUNPATH of exactly `$ORIGIN`, no glibc symbol newer than 2.28 and no debug sections; neither
 * names a build folder), packages each executable with ANGLE's runtime files, admits each package
 * through the product's own gates (`admitWindowsOutput`, `admitLinuxBundle`) against the store
 * ANGLE's manifest pins, checks that tampered copies are refused with the expected code, and runs
 * the Linux build under Xvfb with ANGLE-Vulkan on SwiftShader (in a linux/amd64 container with no
 * network on a Mac, or on the host in CI), saving a screenshot, its sha256, the game's log (which
 * must name ANGLE's Vulkan renderer on SwiftShader) and the loader's trace as evidence. Each X11
 * run is a studio run as ProcessSandbox starts one: `scripts/cross-build-studio-probe.c` (built
 * here with zig, static) hands the game descriptor 3 and a nonce, requires its `ready` event with
 * that nonce, sends `quit` once the screenshot is taken, and requires the answer and exit 0. The
 * Ubuntu run also sets a Wayland session's variables (`XDG_SESSION_TYPE=wayland`, a
 * `WAYLAND_DISPLAY` with no compositor) beside Xvfb's `DISPLAY`, as GNOME and KDE do with
 * XWayland: an exported game must still open its window on X11 there.
 *
 *   node scripts/cross-build-smoke.ts [--targets windows-x64,linux-x64] [--run docker|host|none] [--floor]
 *     [--wayland] [--export] [--fetch] [--toolchains <dir>] [--work <dir>] [--evidence <dir>] [--cmake <bin>]
 *     [--ninja <bin>] [--zig <bin>] [--readobj <bin>] [--raylib <src>] [--angle-windows <dir>]
 *     [--angle-linux <dir>] [--sysroot <dir>]
 *   node scripts/cross-build-smoke.ts --repro [--allow-pdb-difference] [--work <dir>] [--evidence <dir>]
 *     [--cmake <bin>] [--ninja <bin>] [--zig <bin>] [--readobj <bin>] [--raylib <src>] [--angle-windows <dir>]
 *   node scripts/cross-build-smoke.ts --from-archive <Game-windows-x64.zip|game-linux-x64.tar.gz>
 *     [--run docker|host|none] [--floor] [--fetch] [--work <dir>] [--evidence <dir>] [--angle-windows <dir>]
 *     [--angle-linux <dir>]
 *
 * `--from-archive` takes an exported archive instead of building: it is listed and every name
 * planned by the toolchain store's own reader (`archive.ts`: no link of any kind, no absolute or
 * climbing name) before anything is written, extracted, its `SHA256SUMS` must list every file
 * with its digest, the extracted folder is gated and tampered as a build is, and a Linux archive
 * is run as above. `--export` packs each build with the product's own exporters
 * (`exportWindowsZip`, `exportLinuxTarball`) from the build's `out/` and store-shaped inputs (the
 * pinned ANGLE folders with their manifests, zig's folder, raylib's source, and a sysroot folder
 * holding the Wayland protocol code the build compiled, with its manifest) into `<work>/export/`,
 * then checks each archive as `--from-archive` does; the Linux runs then start the game from the
 * extracted tarball, not from the build. `--repro` builds the Windows game twice, raylib's
 * prebuild included, in two folders of different names and lengths under `<work>/repro/`, and
 * requires a byte-identical `game.exe` and `game.pdb` (`--allow-pdb-difference` records a
 * differing `game.pdb` as a measured limit instead of a failure).
 *
 * Tools default to the developer's pinned toolchains (`GENEX_DEV_TOOLCHAINS`, else
 * `.studio-dev/toolchains`); each ANGLE folder must be the build `native/angle/bundle-lock.json`
 * pins, every file its manifest's digest (the toolchain store's own `verifyAngleFolder`). The
 * Linux prebuild compiles GLFW against X11 and Wayland headers taken once from a throwaway
 * `almalinux:8` linux/amd64 container pinned by digest (the glibc floor's own headers), whose
 * package versions must match the pinned ones; GLFW's Wayland protocol code is generated by that
 * image's wayland-scanner once into `glfw-wayland-<sha12>/` beside the sysroot. A run image that
 * lacks the run's packages is prepared once (installed, then committed as a local
 * `genex-cross-run:<kind>-<sha12>` image) and reused. Every container runs with `--network none`
 * except those one-time fetches and preparations, which run only with `--fetch` (CI's fresh
 * runner): without it a missing sysroot, protocol folder or run image refuses the smoke. `--floor`
 * also runs the Linux build in the `almalinux:8` image; `--wayland` runs it under a headless sway
 * compositor in `ubuntu:24.04` with no X server (headless Weston advertises no `wl_seat`, and
 * raylib 6.0's GLFW 3.4 dereferences the missing seat), screenshotting it with grim; `--run none
 * --wayland` runs only that. Nothing outside the work, evidence, sysroot and protocol folders is
 * written, and nothing is removed but an earlier run's probe markers in its own run folder.
 */
