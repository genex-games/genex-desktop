/** The files `--repro` compares, in the lane's `out/` (the game) and the prebuild's output (raylib). */
const REPRO_FILES = ["game.exe", "game.pdb", "libraylib.a"] as const;
type ReproFile = (typeof REPRO_FILES)[number];

/**
 * One Windows build in `folder`: the template and raylib's source copied into it (cloned where the
 * filesystem can), so the two builds share no source, build or output folder; zig and its cache
 * are shared. Returns each compared file's digest and the build folders its bytes name.
 */
async function reproBuild(folder: string, tools: Tools, context: Pick<Context, "evidence" | "digest" | "env">) {
  const target = CrossTarget.WindowsX64;
  const source = path.join(folder, "game");
  const raylibSource = path.join(folder, "raylib-src");
  for (const [from, to] of [
    [TEMPLATE, source],
    [tools.raylib, raylibSource],
  ] as const)
    await cp(from, to, { recursive: true, force: true, mode: FS.COPYFILE_FICLONE });
  const copied = { ...tools, raylib: raylibSource };
  const buildRoots = [folder, REPO, path.dirname(tools.raylib)];
  const built: Context = { ...context, tools: copied, work: folder, protocols: null, source, buildRoots };
  await mkdir(path.join(folder, target), { recursive: true });
  const raylib = await prebuildRaylib(target, built);
  const { out } = await buildGame(target, built, raylib);
  const files: Record<ReproFile, string> = {
    "game.exe": path.join(out, "game.exe"),
    "game.pdb": path.join(out, "game.pdb"),
    "libraylib.a": raylib.lib,
  };
  const digests: Partial<Record<ReproFile, string>> = {};
  const named: Partial<Record<ReproFile, string[]>> = {};
  for (const name of REPRO_FILES) {
    const bytes = await readFile(files[name]).catch((error: NodeJS.ErrnoException) => {
      if (name === "game.pdb" && error.code === "ENOENT") return null;
      throw error;
    });
    if (!bytes) continue;
    digests[name] = sha256(bytes);
    named[name] = buildRoots.filter((root) => bytes.includes(root));
  }
  return { folder, digests, named };
}

/**
 * The Windows game built twice in two folders: `game.exe` must be byte-identical and name no build
 * folder, `game.pdb` identical unless `--allow-pdb-difference` records it as a measured limit;
 * raylib's archive is reported, not required (no export ships it).
 */
function reproDifference(file: ReproFile, a: string, b: string): string | null {
  if (file === "game.pdb" && (!a || !b))
    return "The stripped Windows build emits no game.pdb: PDB reproducibility is unmeasured.";
  if (a === b || file === "libraylib.a") return null;
  return MESSAGE.NotReproducible(file, a, b);
}

async function reproduce(values: Record<string, string | boolean | undefined>, options: Options, work: string) {
  const tools = toolsFrom(values);
  await pinnedAngleManifest(CrossTarget.WindowsX64, tools.angle[CrossTarget.WindowsX64]);
  const context = { evidence: "", digest: smokeDigest(), env: crossBuildEnv(path.join(work, "zig-cache")) };
  const builds = [];
  for (const name of REPRO_FOLDERS) builds.push(await reproBuild(path.join(work, "repro", name), tools, context));
  const [first, second] = builds;
  const failures: string[] = [];
  const limits: string[] = [];
  for (const file of REPRO_FILES) {
    const a = first?.digests[file] ?? "";
    const b = second?.digests[file] ?? "";
    const sentence = reproDifference(file, a, b);
    if (!sentence) continue;
    if (file === "game.pdb" && options.allowPdbDifference) limits.push(sentence);
    else failures.push(sentence);
  }
  for (const build of builds) {
    const roots = build.named["game.exe"] ?? [];
    if (roots.length) failures.push(MESSAGE.ReproNames(`${build.folder}/game.exe`, roots));
  }
  const identical = Object.fromEntries(
    REPRO_FILES.map((file) => [
      file,
      first?.digests[file] && second?.digests[file] ? first.digests[file] === second.digests[file] : null,
    ]),
  );
  return { repro: { target: CrossTarget.WindowsX64, builds, identical, limits }, tampers: [], runs: {}, failures };
}

// ---------- exported archives (--from-archive and --export) ----------

/** Every file under `root` (links included, as found), relative with `/`, sorted. */
async function filesUnder(root: string, rel = ""): Promise<string[]> {
  const found: string[] = [];
  for (const entry of await readdir(path.join(root, rel), { withFileTypes: true })) {
    const child = rel ? `${rel}/${entry.name}` : entry.name;
    if (entry.isDirectory()) found.push(...(await filesUnder(root, child)));
    else found.push(child);
  }
  return found.sort();
}

/**
 * `SHA256SUMS` beside an exported game checked file by file: it must exist, list a digest for
 * every other file in the folder, and every name it lists must be inside the folder and match.
 */
async function checkSums(root: string): Promise<{ checked: number; failures: string[] }> {
  const file = path.join(root, SUMS_FILE);
  if (!existsSync(file)) return { checked: 0, failures: [MESSAGE.NoSumsFile] };
  const lines = (await readFile(file, "utf8")).split("\n").filter((line) => line !== "");
  if (lines.length === 0) return { checked: 0, failures: [MESSAGE.NoSums] };
  const failures: string[] = [];
  const listed = new Set<string>();
  for (const line of lines) {
    const match = /^([0-9a-f]{64}) {2}(.+)$/.exec(line);
    const name = match?.[2] ?? line;
    listed.add(name);
    const target = match ? path.join(root, name) : null;
    const inside = target !== null && isInside(root, target) && existsSync(target);
    const same = inside && match !== null && sha256(await readFile(target)) === match[1];
    if (!same) failures.push(MESSAGE.Sums(name));
  }
  const unlisted = (await filesUnder(root)).filter((rel) => rel !== SUMS_FILE && !listed.has(rel));
  return { checked: lines.length, failures: [...failures, ...unlisted.map(MESSAGE.Unlisted)] };
}

/**
 * An exported archive extracted once into `<work>/from-archive/<sha12>/` by the store's own reader:
 * every entry listed and planned (no link, no absolute or climbing name, no special file) before
 * anything is written, then extracted into a partial folder renamed into place.
 */
async function extractExport(file: string, format: ArchiveFormat, work: string): Promise<string> {
  const digest = sha256(await readFile(file)).slice(0, 12);
  const folder = path.join(work, "from-archive", digest);
  if (existsSync(folder)) return folder;
  const entries = await listArchive(file, format);
  const link = entries.find(
    (entry) => entry.type === ArchiveEntryType.Symlink || entry.type === ArchiveEntryType.Hardlink,
  );
  if (link) throw new Error(MESSAGE.ArchiveLink(link.name));
  // Absolute, climbing and special entries are refused here, before anything is written.
  planExtraction(entries, { strip: 0, into: "" });
  await mkdir(path.dirname(folder), { recursive: true });
  const staging = await mkdtemp(`${folder}.partial-`);
  await extractArchive(file, format, staging, { strip: 0, into: "" });
  await rename(staging, folder);
  return folder;
}

/** The extracted export's game folder (its one top-level folder) and executable (named after it, else the lane's name). */
async function exportedPackage(folder: string, target: CrossTarget, label: string): Promise<Package> {
  const top = await readdir(folder, { withFileTypes: true });
  const only = top.length === 1 && top[0]?.isDirectory() ? top[0].name : null;
  const root = only === null ? folder : path.join(folder, only);
  const named = only === null ? LANE_EXE[target] : `${only}${EXE_SUFFIX[target]}`;
  const exe = existsSync(path.join(root, named)) ? named : LANE_EXE[target];
  return { target, root, exe, label };
}

/** An exported archive extracted, sum-checked, gated against `inputs.angle`, tampered and (Linux) run. */
async function checkArchive(
  file: string,
  inputs: { angle: string; zig: string },
  options: Options,
  work: string,
  evidence: string,
) {
  const { target, format } = archiveTarget(file);
  const folder = await extractExport(file, format, work);
  const pkg = await exportedPackage(folder, target, `archive-${path.basename(folder)}`);
  const sums = await checkSums(pkg.root);
  const product = await gateAndTamper(pkg, inputs.angle, work);
  const linux = target === CrossTarget.LinuxX64;
  const runs = linux ? await linuxRuns(pkg, work, evidence, options, inputs.zig) : {};
  const archive = {
    file,
    sha256: sha256(await readFile(file)),
    target,
    root: pkg.root,
    exe: pkg.exe,
    sums: sums.checked,
  };
  const failures = [...sums.failures, ...product.failures];
  return { archive, product: product.gate, tampers: product.tampers, runs, failures };
}

/** `--from-archive`: one exported archive checked against the developer's store ANGLE. */
async function fromArchive(
  file: string,
  values: Record<string, string | boolean | undefined>,
  options: Options,
  work: string,
  evidence: string,
) {
  const { target } = archiveTarget(file);
  const inputs = { angle: angleFrom(values)[target], zig: pickTool(values, "zig", "zig-0.16.0/zig") };
  const checked = await checkArchive(file, inputs, options, work, evidence);
  const results = { [target]: { package: checked.archive.root, product: checked.product } };
  const { archive, tampers, runs, failures } = checked;
  return { archive, results, tampers, runs, failures };
}

/** The run the options ask for. */
function outcomeOf(
  values: Record<string, string | boolean | undefined>,
  options: Options,
  work: string,
  evidence: string,
) {
  if (options.fromArchive) return fromArchive(options.fromArchive, values, options, work, evidence);
  if (options.repro) return reproduce(values, options, work);
  return buildAll(values, options, work, evidence);
}

async function main(): Promise<void> {
  const { values } = parseArgs({ options: OPTIONS, allowPositionals: false });
  const options = optionsFrom(values);
  const work = path.resolve(String(values.work ?? path.join(REPO, ".studio-dev", "cross-build-work")));
  const evidence = path.resolve(String(values.evidence ?? path.join(REPO, ".studio-dev", "evidence", "cross-build")));
  await mkdir(work, { recursive: true });
  await mkdir(evidence, { recursive: true });
  const started = Date.now();
  const outcome = await outcomeOf(values, options, work, evidence);
  const elapsed = (Date.now() - started) / SECOND_MS;
  const summary = { at: new Date().toISOString(), seconds: elapsed, ...outcome };
  await writeFile(path.join(evidence, "summary.json"), `${JSON.stringify(summary, null, 2)}\n`);
  const runFailures = Object.entries(outcome.runs).flatMap(([name, result]) =>
    result.failures.map((failure) => `${name}: ${failure}`),
  );
  const failures = [...outcome.failures, ...runFailures];
  if (failures.length) throw new Error(failures.join("\n"));
  console.log(MESSAGE.Done(evidence));
}

await main();
