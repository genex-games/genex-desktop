/** The smoke's own lock digest: every module and toolchain file it writes names it. */
const smokeDigest = () => sha256(`cross-build-smoke\n${canonicalJson(readRecipe())}`);

/** Every requested target built, gated and tampered, then exported and checked (`--export`) or the Linux build run. */
async function buildAll(
  values: Record<string, string | boolean | undefined>,
  options: Options,
  work: string,
  evidence: string,
) {
  const tools = toolsFrom(values);
  const linux = options.targets.includes(CrossTarget.LinuxX64) ? await linuxInputs(tools, work, options.fetch) : null;
  const env = crossBuildEnv(path.join(work, "zig-cache"));
  const context: Context = {
    ...{ tools, work, evidence, digest: smokeDigest(), env },
    ...{ protocols: linux?.protocols ?? null, source: TEMPLATE, buildRoots: buildRootsOf(tools, work) },
  };
  const results: Record<string, unknown> = {};
  const tampers: unknown[] = [];
  const failures: string[] = [];
  const outs = new Map<CrossTarget, string>();
  let linuxPackage: Package | null = null;
  for (const target of options.targets) {
    const built = await crossBuild(target, context);
    results[target] = built.summary;
    tampers.push(...built.tampers);
    failures.push(...built.failures);
    outs.set(target, built.out);
    if (target === CrossTarget.LinuxX64) linuxPackage = built.packaged;
  }
  const exported = options.export ? await exportAll(context, outs, options) : null;
  // With --export the Linux runs start the game from the extracted tarball, not from the build.
  const runPackage = exported === null ? linuxPackage : null;
  const runs = runPackage ? await linuxRuns(runPackage, work, evidence, options, tools.zig) : (exported?.runs ?? {});
  tampers.push(...(exported?.tampers ?? []));
  failures.push(...(exported?.failures ?? []));
  const zigVersion = (await exec("zig version", tools.zig, ["version"], path.join(work, "zig-version.log"))).trim();
  const exports = exported ? { exports: exported.exports, archives: exported.archives } : {};
  return { zig: zigVersion, tools, linux, results, ...exports, tampers, runs, failures };
}

