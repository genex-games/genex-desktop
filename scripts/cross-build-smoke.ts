/** Each ANGLE folder's verification, done once: a tamper row checks a copy of the game, never ANGLE. */
const verifiedAngles = new Map<string, Promise<unknown>>();

/**
 * The store ANGLE's manifest, refused unless the folder is the build `native/angle/bundle-lock.json`
 * pins: the pinned manifest, exactly its files, each its digest (`verifyAngleFolder`).
 */
function pinnedAngleManifest(target: CrossTarget, angle: string): Promise<unknown> {
  const known = verifiedAngles.get(angle);
  if (known) return known;
  const verified = verifyAngleFolder(angle, ANGLE_TARGET[target], { bundled: false }).then(async () =>
    JSON.parse(await readFile(path.join(angle, ANGLE_MANIFEST), "utf8")),
  );
  verifiedAngles.set(angle, verified);
  return verified;
}

/** The lock's store ANGLE for `target` as the exporters and admission take it: its folder and pinned manifest digest. */
const crossAngle = (target: CrossTarget, dir: string): CrossAngle => ({
  dir,
  manifestSha256: BUNDLE_LOCK.targets[ANGLE_TARGET[target]].manifestSha256,
});

/** A refusal in the gate's own fields. */
const refusedAnswer = (refusal: string, reason: string | null, file: string, detail: string): GateAnswer => ({
  ok: false,
  refusal,
  reason,
  file,
  detail,
  facts: null,
});

/** The Windows gate (`admitWindowsOutput`) over `root`, pinned to the manifest's DLL digests. */
async function windowsGate(root: string, exe: string, manifest: unknown, angle: string): Promise<GateAnswer> {
  const pins = windowsAnglePins(manifest);
  if (pins === null) throw new Error(MESSAGE.NoPins(angle));
  const admission = await admitWindowsOutput(root, { exe, pins });
  if (!admission.ok) return refusedAnswer(admission.refusal, admission.problem, admission.file, admission.detail);
  const { bundle } = admission;
  const facts = {
    imports: bundle.exe.image.imports,
    delayImports: bundle.exe.image.delayImports,
    suppliedAngle: bundle.suppliedAngle,
    assets: bundle.assets.length,
    ignored: bundle.ignored,
  };
  return { ok: true, refusal: null, reason: null, file: null, detail: null, facts };
}

/** The Linux gate (`admitLinuxBundle`) over `root`, with the manifest's host files. */
async function linuxGate(root: string, exe: string, manifest: unknown): Promise<GateAnswer> {
  const admission = await admitLinuxBundle({ root, exe, hostFiles: linuxHostFiles(manifest) });
  if (!admission.ok) return refusedAnswer(admission.refusal, admission.reason, admission.file, admission.detail);
  const { bundle } = admission;
  const facts = {
    needed: bundle.image.needed,
    runpath: bundle.image.runpath,
    maxGlibc: bundle.maxGlibc,
    files: bundle.files,
    hostCopies: bundle.hostCopies,
  };
  return { ok: true, refusal: null, reason: null, file: null, detail: null, facts };
}

/** What the product's host gate answers for `pkg` against the store ANGLE in `angle`. */
async function productGate(pkg: Package, angle: string): Promise<GateAnswer> {
  const manifest = await pinnedAngleManifest(pkg.target, angle);
  return pkg.target === CrossTarget.WindowsX64
    ? windowsGate(pkg.root, pkg.exe, manifest, angle)
    : linuxGate(pkg.root, pkg.exe, manifest);
}

/** Every occurrence of `from` in `bytes` replaced by `to` (as long, or padded with NULs); throws when there is none. */
function replaceAll(bytes: Buffer, from: string, to: string, missing: string): Buffer {
  const needle = Buffer.from(from, "latin1");
  const patch = Buffer.alloc(needle.length);
  patch.write(to, "latin1");
  const out = Buffer.from(bytes);
  let at = out.indexOf(needle);
  if (at < 0) throw new Error(missing);
  while (at >= 0) {
    patch.copy(out, at);
    at = out.indexOf(needle, at + needle.length);
  }
  return out;
}

/** Renames a Windows import (the first one at least as long as `opengl32.dll`, not ANGLE's) to `opengl32.dll`. */
async function tamperOpengl32(dir: string, exe: string): Promise<void> {
  const file = path.join(dir, exe);
  const read = readPe(await readFile(file));
  const victim = read.ok
    ? read.image.imports.find((name) => name.length >= OPENGL32.length && name.toLowerCase() !== GLES_DLL)
    : undefined;
  if (victim === undefined) throw new Error(MESSAGE.NoVictim(exe));
  const patched = replaceAll(await readFile(file), `${victim}\0`, OPENGL32, MESSAGE.NoVictim(exe));
  const after = readPe(patched);
  if (!after.ok || !after.image.imports.includes(OPENGL32)) throw new Error(MESSAGE.Untampered(Tamper.Opengl32Import));
  await writeFile(file, patched);
}

/** Rewrites a Linux game's `$ORIGIN` RUNPATH to a writable folder outside the bundle. */
async function tamperRunpath(dir: string, exe: string): Promise<void> {
  const file = path.join(dir, exe);
  const patched = replaceAll(await readFile(file), `${ORIGIN}\0`, HIJACKED_RUNPATH, MESSAGE.NoOrigin(exe));
  if (!parseElf(patched).runpath.includes(HIJACKED_RUNPATH))
    throw new Error(MESSAGE.Untampered(Tamper.RunpathNotOrigin));
  await writeFile(file, patched);
}

/** Adds a copy of one of the bundle's own libraries under a name the host does not supply. */
const tamperExtra = (source: string, extra: string) => async (dir: string) => {
  await writeFile(path.join(dir, extra), await readFile(path.join(dir, source)));
};

interface TamperRow {
  name: Tamper;
  expected: NativeRefusal;
  apply: (dir: string, exe: string) => Promise<void>;
}

const TAMPER_ROWS = {
  [CrossTarget.WindowsX64]: [
    { name: Tamper.Opengl32Import, expected: NativeRefusal.ImportsOpengl32, apply: tamperOpengl32 },
    { name: Tamper.ExtraDll, expected: NativeRefusal.ExtraPe, apply: tamperExtra(WindowsRuntimeFile.Egl, "extra.dll") },
  ],
  [CrossTarget.LinuxX64]: [
    { name: Tamper.RunpathNotOrigin, expected: NativeRefusal.RunpathNotOrigin, apply: tamperRunpath },
    {
      name: Tamper.ExtraSharedObject,
      expected: NativeRefusal.ExtraSharedObject,
      apply: tamperExtra(LinuxRuntimeFile.Egl, "libextra.so"),
    },
  ],
} as const satisfies Record<CrossTarget, readonly TamperRow[]>;

/**
 * Each tamper row on its own copy of `pkg` (cloned where the filesystem can, overwritten in place
 * on the next run, never removed) and the product gate's answer, which must be the row's refusal.
 */
async function tamperRows(pkg: Package, angle: string, work: string) {
  const rows = [];
  for (const row of TAMPER_ROWS[pkg.target]) {
    const dir = path.join(work, "tamper", pkg.label, row.name);
    await cp(pkg.root, dir, { recursive: true, force: true, mode: FS.COPYFILE_FICLONE });
    await row.apply(dir, pkg.exe);
    const answer = await productGate({ ...pkg, root: dir }, angle);
    const got = answer.ok ? "admitted" : (answer.refusal ?? "refused");
    rows.push({
      target: pkg.target,
      row: row.name,
      expected: row.expected,
      got,
      reason: answer.reason,
      ok: got === row.expected,
    });
  }
  return rows;
}

/** The product gate over `pkg` and every tamper row, with the failures they add. */
async function gateAndTamper(pkg: Package, angle: string, work: string) {
  const gate = await productGate(pkg, angle);
  const tampers = await tamperRows(pkg, angle, work);
  const failures = [
    ...(gate.ok ? [] : [MESSAGE.Refused(pkg.target, gate.refusal, gate.file, gate.detail)]),
    ...tampers.filter((row) => !row.ok).map((row) => MESSAGE.Tampered(row.row, row.expected, row.got)),
  ];
  return { gate, tampers, failures };
}

