/** The Linux runs the options ask for: Ubuntu 24.04 (container or host), then AlmaLinux 8 and Wayland when asked. */
async function linuxRuns(pkg: Package, work: string, evidence: string, options: Options, zig: string) {
  const runs: Record<string, Awaited<ReturnType<typeof runEvidence>> & { image: unknown }> = {};
  const planned: { kind: RunKind; mode: RunMode }[] = [];
  if (options.run !== RunMode.None) planned.push({ kind: RUN_KINDS.ubuntu, mode: options.run });
  if (options.floor) planned.push({ kind: RUN_KINDS.floor, mode: RunMode.Docker });
  if (options.wayland) planned.push({ kind: RUN_KINDS.wayland, mode: RunMode.Docker });
  const probe = planned.length ? await studioProbe(zig, work) : "";
  for (const { kind, mode } of planned) {
    const plan = { mode, kind, probe, fetch: options.fetch };
    const { out, image } = await runLinux(pkg, path.join(work, `run-${kind.name}`), plan);
    const result = await runEvidence(out, kind, mode === RunMode.Host ? pkg.root : "/game", evidence);
    runs[kind.name] = { ...result, image };
  }
  return runs;
}

/** One target end to end: prebuild, game, readobj facts, the product gate, tamper rows and package digests. */
async function crossBuild(target: CrossTarget, context: Context) {
  await mkdir(path.join(context.work, target), { recursive: true });
  const raylib = await prebuildRaylib(target, context);
  const { exe, pkg, out } = await buildGame(target, context, raylib);
  const gate = target === CrossTarget.WindowsX64 ? await windowsFacts(exe, context) : await linuxFacts(exe, context);
  if (gate.failures.length) throw new Error(MESSAGE.Gate(target, gate.failures));
  const files = [path.basename(exe), ...crossRuntimeFiles(target)];
  const sums = await Promise.all(files.map(async (file) => `${sha256(await readFile(path.join(pkg, file)))}  ${file}`));
  await writeFile(path.join(context.evidence, `${target}.SHA256SUMS`), `${sums.join("\n")}\n`);
  const packaged: Package = { target, root: pkg, exe: path.basename(exe), label: target };
  const product = await gateAndTamper(packaged, context.tools.angle[target], context.work);
  const summary = { package: pkg, raylib: raylib.lib, gate: gate.facts, product: product.gate, sha256: sums };
  return { packaged, out, summary, tampers: product.tampers, failures: product.failures };
}

