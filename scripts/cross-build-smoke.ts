/**
 * The image a containerised run uses: `kind.image` when it already holds the run's packages, else
 * a local image prepared once (installed with the network, then committed) and reused after.
 */
async function runImage(kind: RunKind, logs: string, fetch: boolean): Promise<{ image: string; preparedNow: boolean }> {
  const tag = `${PREPARED_REPOSITORY}:${kind.name}-${sha256(`${kind.image}\n${installCommand(kind)}`).slice(0, 12)}`;
  if ((await collect("docker", ["image", "inspect", tag])).code === 0) return { image: tag, preparedNow: false };
  const probe = [
    "run",
    "--rm",
    "--network",
    "none",
    "--platform",
    PLATFORM,
    kind.image,
    "sh",
    "-c",
    readyCommand(kind),
  ];
  if ((await collect("docker", probe)).code === 0) return { image: kind.image, preparedNow: false };
  // Installing packages is the one step of a run that uses the network: only with --fetch.
  if (!fetch) throw new Error(MESSAGE.NeedsFetch(`the ${kind.name} run image`));
  const container = `genex-cross-prep-${process.pid}-${Date.now()}`;
  const log = path.join(logs, `prepare-${kind.name}.log`);
  try {
    const install = ["run", "--name", container, "--platform", PLATFORM, kind.image, "sh", "-c", installCommand(kind)];
    await exec(`prepare ${kind.name}`, "docker", install, log);
    await exec(`commit ${kind.name}`, "docker", ["commit", container, tag], `${log}.commit`);
  } finally {
    await collect("docker", ["rm", container]);
  }
  return { image: tag, preparedNow: true };
}

