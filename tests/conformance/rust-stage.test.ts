const REGISTRY = "registry+https://github.com/rust-lang/crates.io-index";

/** One `[[package]]` of a base lock, as cargo writes it. */
function pkg(name: string, version: string, deps: string[] = [], source: string | null = REGISTRY): string {
  const lines = ["[[package]]", `name = "${name}"`, `version = "${version}"`];
  if (source) lines.push(`source = "${source}"`, `checksum = "${"ab".repeat(32)}"`);
  if (deps.length > 0) lines.push("dependencies = [", ...deps.map((dep) => ` "${dep}",`), "]");
  return lines.join("\n");
}

/**
 * The store's lock line: genex with its closure, both allowlisted crates, two `rand_core`s the
 * closure keeps, and a `hashbrown 0.14.5` only an unrelated package reaches, so the game's lock
 * drops it and names the remaining `hashbrown` without a version, as cargo does.
 */
const BASE_LOCK = [
  "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4",
  pkg("fastrand", "2.5.0"),
  pkg("genex", GENEX_VERSION, ["genex-core", "hashbrown 0.15.0", "rand_core 0.6.4"]),
  pkg("genex-core", GENEX_VERSION, ["rand_core 0.9.0"]),
  pkg("hashbrown", "0.14.5"),
  pkg("hashbrown", "0.15.0"),
  pkg("noise", "0.9.0", ["rand_core 0.6.4"]),
  pkg("rand_core", "0.6.4"),
  pkg("rand_core", "0.9.0"),
  pkg("unrelated", "1.0.0", ["hashbrown 0.14.5"]),
].join("\n\n");

const PINS = { genexVersion: GENEX_VERSION, baseLock: BASE_LOCK };

/** A game made from the template, titled, with `files` written over it (`null` removes one). */
async function makeGame(files: Record<string, string | null> = {}): Promise<string> {
  const game = path.join(await tmpDir("rust-stage-game-"), "game");
  await cp(TEMPLATE, game, { recursive: true });
  for (const name of ["genex.toml", path.join("src", "main.rs")]) {
    const file = path.join(game, name);
    await writeFile(file, (await readFile(file, "utf8")).replaceAll("__GAME_TITLE__", "Pond"));
  }
  for (const [rel, text] of Object.entries(files)) {
    const file = path.join(game, ...rel.split("/"));
    if (text === null) await rm(file, { force: true });
    else {
      await mkdir(path.dirname(file), { recursive: true });
      await writeFile(file, text);
    }
  }
  return game;
}

/** A fresh stage path beside nothing the game owns. */
async function stagePath(): Promise<string> {
  return path.join(await tmpDir("rust-stage-out-"), "stage");
}

/** Stage `game` for `target` (the Mac by default). */
function stage(game: string, at: string, target: BuildTarget = BuildTarget.Mac): Promise<StageResult> {
  return stageRustGame({ source: game, stage: at, target, pins: PINS });
}

/** A staged result, or a failure naming its refusal. */
function staged(result: StageResult) {
  assert.ok(result.ok, `refused: ${result.ok ? "" : `${result.code} ${result.detail}`}`);
  return result;
}

const exists = (p: string) =>
  lstat(p).then(
    () => true,
    () => false,
  );

/** A game whose `src/game.rs` gains `code` at its end. */
const withGameCode = (code: string) => async () => {
  const game = await makeGame();
  const file = path.join(game, "src", "game.rs");
  await writeFile(file, `${await readFile(file, "utf8")}\n${code}\n`);
  return game;
};

