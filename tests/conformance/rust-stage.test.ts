/**
 * The Rust lane's inputs (`src/main/rust-stage.ts`, `src/main/rust-manifest.ts`): a game's `src/`
 * and `assets/` (and the WGSL sources its `genex.toml` names) are copied by the host into a
 * link-free stage, every Rust file in the copy is read for `include!`, `include_str!`,
 * `include_bytes!`, `#[path]` and `env!` reaching outside it, and the host writes the cargo
 * manifest and lock there itself. A refused game leaves nothing staged, a previous stage included.
 *
 * Hostile rows: a symlinked facet, folder or asset, a hard link, an absolute or climbing include,
 * an include of a key file the stage leaves out, a non-literal or renamed include, an escaped
 * literal, a `#[path]` (plain or under `cfg_attr`) leaving the stage, `env!` of a host variable,
 * an unknown native feature and a web build of a game that declares one. The manifest never holds
 * a host path, and the lock is the same bytes however often and wherever it is written.
 */
