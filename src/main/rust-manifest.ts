/**
 * The cargo manifest and lock the host writes for a Rust · wgpu game, from its `genex.toml` alone
 * (plan "Lane rules"). A game folder never holds a `Cargo.toml`, so nothing a game writes reaches
 * cargo's configuration: the manifest names one binary at `src/main.rs` of the stage, no build
 * script, no auto-discovered targets, `genex = "=X.Y.Z"` (resolved through the store's source
 * replacement, so no host path enters it) and the allowlisted crates the game asked for.
 *
 * The lock is derived from the store's lock line (a cargo-written `Cargo.lock` over the vendored
 * registry): the game's package plus the closure of its dependencies, sorted and spelled as cargo
 * writes a version 4 lock, so the same `genex.toml` and lock line give the same bytes on every
 * host, in every stage folder, on every run. On a lock line cargo resolved for the same crate set
 * the result is cargo's own lock, byte for byte, and `--locked` accepts it. The closure is a graph
 * walk, not a feature resolution: on a wider lock line (the runtime workspace's, which carries
 * dev-dependencies and features other members turn on) it keeps entries cargo would drop, never
 * a different version, so the lane's offline re-resolution before `--locked` (M2.1) only prunes.
 *
 * `env!` and `option_env!` in a game read only cargo's package variables, which this manifest
 * fixes (`RUST_ENV_MACRO_NAMES`, enforced by the stage); the lane runs cargo with
 * `RUST_FIXED_ENV` on top of its own toolchain variables.
 *
 * An ejected game (extension ladder level 5, `rust-eject.ts`) links its own fork of the engine:
 * the manifest pins `genex` at the release the person ejected (`[engine] ejected_from`, whatever
 * the store's lock line now pins) and patches each forked crate to `engine/<crate>` in the stage,
 * and the lock names those crates as path packages. The studio's transport and the phone shells
 * stay the store's (`RUST_ENGINE_KEPT_CRATES`).
 */
