/**
 * The game's `Cargo.toml`, from its checked `genex.toml` and the pinned genex release, linking the
 * facade in `flavour` (an export's, unless the build is a dev one). An ejected game's `fork` pins
 * its own release instead and patches every forked crate to `engine/<crate>`.
 */
export function cargoManifest(
  manifest: GenexToml,
  genexVersion: string,
  flavour: RustFlavour = RustFlavour.Export,
  facade: RustFacadePackage = RustFacadePackage.Native,
  fork: EngineFork | null = null,
): string {
  const version = fork?.version ?? genexVersion;
  pinnedGenex(version);
  const genex = { name: FACADE_NAME, version: `=${version}` };
  const dependencies = [genex, ...manifest.crates].sort((a, b) => compareText(a.name, b.name));
  const line = (dependency: { name: string; version: string }) =>
    dependency === genex
      ? facadeLine(genex.version, flavour, facade)
      : `${dependency.name} = ${quote(dependency.version)}`;
  return [
    "# Written by Genex from genex.toml before every build: a game folder holds no cargo manifest.",
    "[package]",
    `name = ${quote(RUST_GAME_PACKAGE)}`,
    `version = ${quote(RUST_GAME_VERSION)}`,
    `edition = ${quote(RUST_EDITION)}`,
    "publish = false",
    "build = false",
    "autolib = false",
    "autobins = false",
    "autoexamples = false",
    "autotests = false",
    "autobenches = false",
    "",
    "[[bin]]",
    `name = ${quote(RUST_GAME_BIN)}`,
    `path = ${quote("src/main.rs")}`,
    "",
    "[dependencies]",
    ...dependencies.map(line),
    "",
    ...forkPatch(fork),
  ].join("\n");
}

/** The `[patch.crates-io]` rows pointing each forked crate at `engine/<crate>`; none for the store's engine. */
function forkPatch(fork: EngineFork | null): string[] {
  if (fork === null) return [];
  const crates = RUST_ENGINE_CRATES.filter((name) => fork.crates.includes(name));
  const row = (name: string) => `${quote(name)} = { path = ${quote(`${RUST_ENGINE_FOLDER}/${name}`)} }`;
  return ["[patch.crates-io]", ...crates.map(row), ""];
}

/**
 * The `genex = …` line: the facade at the pinned version, with its `studio` feature in the dev
 * flavour, or the web shell's crate under the facade's name for a web build.
 */
function facadeLine(version: string, flavour: RustFlavour, facade: RustFacadePackage): string {
  if (facade !== RustFacadePackage.Native)
    return `${FACADE_NAME} = { package = ${quote(facade)}, version = ${quote(version)} }`;
  if (flavour === RustFlavour.Dev)
    return `${FACADE_NAME} = { version = ${quote(version)}, features = [${quote(STUDIO_FEATURE)}] }`;
  return `${FACADE_NAME} = ${quote(version)}`;
}

/** A game's lock and its sha256, or why the lock line cannot give one. */
export type GameLock =
  | { ok: true; text: string; digest: string }
  | { ok: false; code: RustManifestCode; detail: string };

/** The game's `Cargo.lock`: its package and the closure of its dependencies in the store's lock line. */
export function gameCargoLock(
  manifest: GenexToml,
  pins: { genexVersion: string; baseLock: string; facade?: RustFacadePackage; fork?: EngineFork | null },
): GameLock {
  const fork = pins.fork ?? null;
  const version = fork?.version ?? pins.genexVersion;
  pinnedGenex(version);
  const read = readLock(pins.baseLock);
  if (read === null) return lockRefusal(RustManifestCode.LockUnreadable, "the store's lock line");
  const packages = fork === null ? read : read.map((found) => asForked(found, fork));
  const facade = pins.facade ?? RustFacadePackage.Native;
  const genex = packages.find((found) => found.name === facade && found.version === version);
  if (genex === undefined) return lockRefusal(RustManifestCode.GenexNotInLock, `${facade} ${version}`);
  const roots = [genex];
  for (const crate of manifest.crates) {
    const chosen = newestMatching(packages, crate.name, crate.version);
    if (chosen === null) return lockRefusal(RustManifestCode.CrateNotInLock, `${crate.name} ${crate.version}`);
    roots.push(chosen);
  }
  const closure = lockClosure(packages, roots);
  const clash = closure === null || closure.some((found) => found.name === RUST_GAME_PACKAGE);
  if (clash) return lockRefusal(RustManifestCode.LockUnreadable, "a dependency the lock line does not hold");
  const game: LockPackage = {
    name: RUST_GAME_PACKAGE,
    version: RUST_GAME_VERSION,
    source: null,
    checksum: null,
    dependencies: [],
  };
  const text = writeLock(
    [...closure, game],
    new Map([[game, roots], ...closure.map((found) => [found, found.resolved] as const)]),
  );
  return { ok: true, text, digest: createHash("sha256").update(text).digest("hex") };
}

/** The genex release a lock line pins: its one `genex` package's version, or null when it holds none, several or no lock. */
export function genexReleaseOf(lockLine: string): string | null {
  const versions = (readLock(lockLine) ?? [])
    .filter((found) => found.name === "genex" && GENEX_VERSION.test(found.version))
    .map((found) => found.version);
  return versions.length === 1 ? (versions[0] ?? null) : null;
}

/** A lock line's package as an ejected game's lock holds it: a forked crate is a path package (no source, no checksum). */
function asForked(found: LockPackage, fork: EngineFork): LockPackage {
  const forked = fork.crates.includes(found.name) && found.version === fork.version;
  return forked ? { ...found, source: null, checksum: null } : found;
}

function lockRefusal(code: RustManifestCode, detail: string): GameLock {
  return { ok: false, code, detail };
}

function pinnedGenex(version: string): void {
  if (!GENEX_VERSION.test(version))
    throw new Error(`the store pins genex ${JSON.stringify(version)}, not a release version`);
}

/** A TOML basic string of a value the host checked (no quote, backslash or control character to escape, but escaped anyway). */
function quote(value: string): string {
  return JSON.stringify(value);
}

// ── The lock line ──────────────────────────────────────────────────────────────────────────────

/** One `[[package]]` of a lock. */
interface LockPackage {
  name: string;
  version: string;
  source: string | null;
  checksum: string | null;
  /** The entries as the lock spells them. */
  dependencies: readonly string[];
}

/** A package of the closure with its dependencies resolved to packages. */
interface ResolvedPackage extends LockPackage {
  resolved: LockPackage[];
}

/** The packages of a version 4 lock, or null when it is not one this module reads. */
function readLock(text: string): LockPackage[] | null {
  let document: TomlTable;
  try {
    document = parseTomlDocument(text);
  } catch {
    return null;
  }
  if (document.version !== LOCK_VERSION || !Array.isArray(document.package)) return null;
  const packages = document.package.map(lockPackage);
  return packages.every((found) => found !== null) ? packages : null;
}

function lockPackage(value: TomlValue): LockPackage | null {
  if (!isTable(value)) return null;
  const { name, version, source = null, checksum = null, dependencies = [] } = value;
  if (typeof name !== "string" || typeof version !== "string" || !SEMVER.test(version)) return null;
  if (!optionalString(source) || !optionalString(checksum) || !Array.isArray(dependencies)) return null;
  const entries = dependencies.filter((dep) => typeof dep === "string");
  if (entries.length !== dependencies.length) return null;
  return { name, version, source, checksum, dependencies: entries };
}

const optionalString = (value: TomlValue | null): value is string | null => value === null || typeof value === "string";

/** The package a lock entry names, when exactly one matches. */
function lockEntry(packages: readonly LockPackage[], entry: string): LockPackage | null {
  const [, name, version, source] = LOCK_DEP.exec(entry) ?? [];
  const matches = packages.filter(
    (found) =>
      found.name === name &&
      (version === undefined || found.version === version) &&
      (source === undefined || found.source === source),
  );
  return matches.length === 1 ? (matches[0] ?? null) : null;
}

/** Every package `roots` reach, each with its dependencies resolved; null when an entry names nothing in the lock. */
function lockClosure(packages: readonly LockPackage[], roots: readonly LockPackage[]): ResolvedPackage[] | null {
  const reached = new Map<LockPackage, ResolvedPackage>();
  const pending = [...roots];
  for (let next = pending.pop(); next !== undefined; next = pending.pop()) {
    if (reached.has(next)) continue;
    const resolved = next.dependencies.map((entry) => lockEntry(packages, entry));
    if (resolved.some((found) => found === null)) return null;
    const children = resolved.filter((found) => found !== null);
    reached.set(next, { ...next, resolved: children });
    pending.push(...children);
  }
  return [...reached.values()];
}

/** The lock text of `packages`, each entry spelled against `packages` alone, as cargo does. */
function writeLock(
  packages: readonly LockPackage[],
  dependencies: ReadonlyMap<LockPackage, readonly LockPackage[]>,
): string {
  const spell = (found: LockPackage) => lockSpelling(packages, found);
  const blocks = [...packages].sort(comparePackages).map((found) => {
    const lines = ["[[package]]", `name = ${quote(found.name)}`, `version = ${quote(found.version)}`];
    if (found.source !== null) lines.push(`source = ${quote(found.source)}`);
    if (found.checksum !== null) lines.push(`checksum = ${quote(found.checksum)}`);
    const deps = [...(dependencies.get(found) ?? [])].sort(compareEntries);
    if (deps.length > 0) lines.push("dependencies = [", ...deps.map((dep) => ` ${quote(spell(dep))},`), "]");
    return `${lines.join("\n")}\n`;
  });
  return [`${LOCK_HEADER}version = ${LOCK_VERSION}\n`, ...blocks].join("\n");
}

/** How a lock names `found`: the name alone when it is the only one, then with its version, then its source. */
function lockSpelling(packages: readonly LockPackage[], found: LockPackage): string {
  const named = packages.filter((other) => other.name === found.name);
  if (named.length === 1) return found.name;
  const versioned = named.filter((other) => other.version === found.version);
  if (versioned.length === 1 || found.source === null) return `${found.name} ${found.version}`;
  return `${found.name} ${found.version} (${found.source})`;
}

function comparePackages(a: LockPackage, b: LockPackage): number {
  return (
    compareText(a.name, b.name) || compareVersions(a.version, b.version) || compareText(a.source ?? "", b.source ?? "")
  );
}

/** Cargo sorts dependency entries by name, then version text, then source. */
function compareEntries(a: LockPackage, b: LockPackage): number {
  return (
    compareText(a.name, b.name) || compareText(a.version, b.version) || compareText(a.source ?? "", b.source ?? "")
  );
}

function compareText(a: string, b: string): number {
  if (a === b) return 0;
  return a < b ? -1 : 1;
}

// ── Versions ───────────────────────────────────────────────────────────────────────────────────

interface Semver {
  numbers: [number, number, number];
  pre: string | null;
}

function semver(version: string): Semver | null {
  const match = SEMVER.exec(version);
  if (match === null) return null;
  return { numbers: [Number(match[1]), Number(match[2]), Number(match[3])], pre: match[4] ?? null };
}

/** Semver order: by number, a pre-release before its release, pre-releases by text. */
function compareVersions(a: string, b: string): number {
  const left = semver(a);
  const right = semver(b);
  if (left === null || right === null) return compareText(a, b);
  for (let at = 0; at < 3; at += 1) {
    const step = (left.numbers[at] ?? 0) - (right.numbers[at] ?? 0);
    if (step !== 0) return Math.sign(step);
  }
  if (left.pre === right.pre) return 0;
  if (left.pre === null) return 1;
  if (right.pre === null) return -1;
  return compareText(left.pre, right.pre);
}

/** The newest release of `name` in the lock that a cargo requirement (`0.9`, `^0.9.0`, `~2.5`, `=2.5.0`) accepts. */
function newestMatching(packages: readonly LockPackage[], name: string, requirement: string): LockPackage | null {
  const bounds = requirementBounds(requirement);
  if (bounds === null) return null;
  const accepted = packages.filter((found) => found.name === name && withinBounds(found.version, bounds));
  return accepted.sort((a, b) => compareVersions(b.version, a.version))[0] ?? null;
}

/** `[lowest accepted, first refused]` of a requirement. */
type Bounds = readonly [[number, number, number], [number, number, number]];

function requirementBounds(requirement: string): Bounds | null {
  const match = REQUIREMENT.exec(requirement);
  if (match === null) return null;
  const operator = match[1] ?? "";
  const given = [match[2], match[3], match[4]].filter((part) => part !== undefined).map(Number);
  const low: [number, number, number] = [given[0] ?? 0, given[1] ?? 0, given[2] ?? 0];
  return [low, upperBound(operator, given)];
}

/** The first version a requirement refuses: bump the last given part (`=`, `~`) or the first non-zero one (caret). */
function upperBound(operator: string, given: readonly number[]): [number, number, number] {
  const bumpAt = bumpedPart(operator, given);
  const upper: [number, number, number] = [0, 0, 0];
  for (let at = 0; at < bumpAt; at += 1) upper[at] = given[at] ?? 0;
  upper[bumpAt] = (given[bumpAt] ?? 0) + 1;
  return upper;
}

/** Which part of a requirement's version its upper bound bumps. */
function bumpedPart(operator: string, given: readonly number[]): number {
  if (operator === "=") return given.length - 1;
  if (operator === "~") return Math.min(1, given.length - 1);
  const firstNonZero = given.findIndex((part) => part !== 0);
  return firstNonZero === -1 ? given.length - 1 : firstNonZero;
}

function withinBounds(version: string, [low, high]: Bounds): boolean {
  const parsed = semver(version);
  if (parsed === null || parsed.pre !== null) return false;
  const text = (numbers: readonly number[]) => numbers.join(".");
  return compareVersions(version, text(low)) >= 0 && compareVersions(version, text(high)) < 0;
}
