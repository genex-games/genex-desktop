//! The gamepad family: which face labels a pad wears (Cross and Circle, A and B, B and A). It is
//! display-only (glyphs, prompts, the Nintendo confirm swap of a UI context) and never changes a
//! reading: the standard mapping still names buttons by position.
//!
//! A family comes from the pad's USB vendor and product ids ([`pad_family`], desktop and Android),
//! from a browser's `Gamepad.id` ([`family_from_web_id`]), from the platform's own category (iOS)
//! or from the host's `input` wire (`family` on a `gamepad` action or a `pads` entry). Anything
//! unknown is [`PadFamily::Generic`].
//!
//! The VID/PID table is ported from SDL's `src/joystick/controller_list.h`
//! (<https://github.com/libsdl-org/SDL>, commit b9d64c45a965edc4b003c160ab446426363e192d,
//! Copyright (C) Valve Corporation, zlib licence). This is an altered version: each SDL controller
//! type is folded into a family, the 11 rows whose type has no family (8BitDo, the unknown
//! non-Steam controller, mobile touch) are left out because they read as Generic anyway, and the
//! names and comments are dropped. Rows keep SDL's order, and the first row of a pair listed twice
//! wins, as in SDL's `GuessControllerType`.
