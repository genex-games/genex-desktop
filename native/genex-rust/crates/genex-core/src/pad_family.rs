/// The face-label family of a gamepad.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum PadFamily {
    /// Unknown, or a pad without a family of its own: position names (South, East).
    #[default]
    Generic,
    /// Xbox 360, Xbox One, Series and Elite pads and their XInput clones: A, B, X, Y.
    Xbox,
    /// DualShock 3 and 4, DualSense and their clones: Cross, Circle, Square, Triangle.
    PlayStation,
    /// Switch and Switch 2 Pro, Joy-Con and licensed pads: B, A, Y, X (confirm on East).
    Nintendo,
    /// Steam Controller and Steam Deck.
    Steam,
}

impl PadFamily {
    /// Every family, in wire order.
    pub const ALL: &'static [PadFamily] =
        &[PadFamily::Generic, PadFamily::Xbox, PadFamily::PlayStation, PadFamily::Nintendo, PadFamily::Steam];

    /// The wire spelling (`input` verb, `state()`, the host's `NativeGamepadFamily`).
    pub const fn as_str(self) -> &'static str {
        match self {
            PadFamily::Generic => "generic",
            PadFamily::Xbox => "xbox",
            PadFamily::PlayStation => "playstation",
            PadFamily::Nintendo => "nintendo",
            PadFamily::Steam => "steam",
        }
    }

    /// The family a wire spelling names exactly (case included); None for any other.
    pub fn from_wire(name: &str) -> Option<PadFamily> {
        PadFamily::ALL.iter().copied().find(|family| family.as_str() == name)
    }
}

/// The longest `Gamepad.id` read; a longer one is Generic (the web shell forwards at most 128).
