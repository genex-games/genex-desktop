/// The family of the pad with USB vendor id `vendor` and product id `product`.
pub fn pad_family(vendor: u16, product: u16) -> PadFamily {
    let id = (u32::from(vendor) << 16) | u32::from(product);
    CONTROLLERS.iter().find(|(known, _)| *known == id).map_or(PadFamily::Generic, |(_, family)| *family)
}

/// 1 to `max` hex digits making the whole of `text`, as a number.
fn hex(text: &[u8], max: usize) -> Option<u16> {
    if text.is_empty() || text.len() > max || !text.iter().all(u8::is_ascii_hexdigit) {
        return None;
    }
    // At most four ASCII hex digits, so both conversions hold.
    u16::from_str_radix(std::str::from_utf8(text).ok()?, 16).ok()
}

/// Chromium's `(... Vendor: 054c Product: 0ce6)`: exactly four digits each.
fn chromium_ids(id: &[u8]) -> Option<(u16, u16)> {
    const VENDOR: &[u8] = b"Vendor: ";
    const PRODUCT: &[u8] = b" Product: ";
    let at = id.windows(VENDOR.len()).position(|window| window == VENDOR)? + VENDOR.len();
    let vendor = hex(id.get(at..at + 4)?, 4)?;
    let rest = id.get(at + 4..)?;
    let product = rest.strip_prefix(PRODUCT)?;
    if product.get(4).is_some_and(u8::is_ascii_hexdigit) {
        return None;
    }
    Some((vendor, hex(product.get(..4)?, 4)?))
}

/// Firefox's `054c-0ce6-DualSense Wireless Controller`: 1 to 4 digits each, unpadded.
fn firefox_ids(id: &[u8]) -> Option<(u16, u16)> {
    let mut parts = id.splitn(3, |&byte| byte == b'-');
    let vendor = hex(parts.next()?, 4)?;
    let product = hex(parts.next()?, 4)?;
    parts.next()?;
    Some((vendor, product))
}

/// The family a browser's `Gamepad.id` names. Chromium and Firefox carry the VID/PID; Chromium's
/// XInput pads on Windows carry only "XInput", which is the Xbox layout; Safari carries a name and
/// stays Generic. An id that is too long or holds a NUL is Generic.
pub fn family_from_web_id(id: &str) -> PadFamily {
    let bytes = id.as_bytes();
    if bytes.is_empty() || bytes.len() > WEB_ID_BYTES_MAX || bytes.contains(&0) {
        return PadFamily::Generic;
    }
    if let Some((vendor, product)) = chromium_ids(bytes).or_else(|| firefox_ids(bytes)) {
        return pad_family(vendor, product);
    }
    if id.contains("(XInput STANDARD GAMEPAD)") {
        return PadFamily::Xbox;
    }
    PadFamily::Generic
}
