//! EP-X1: the town cells' nav islands are baked offline (here, from `world::island_input` with the
//! game's nav config) and committed as `assets/islands/<x>_<z>.navmesh` with the table
//! `src/island_table.rs` that builds them into the binary. The row checks the committed bytes equal
//! a fresh bake, so an edit to the placement file or the bake input that is not re-baked fails here,
//! and that each island reads back with `NavIsland::from_bytes` to the baked tiles.
//!
//! Re-bake after a change:
//!
//!   GENEX_FRONTIER_WRITE_ISLANDS=1 node scripts/toolchains/rust-env.ts -- cargo test -p frontier \
//!     --release --offline --test islands

use std::path::PathBuf;

use frontier_game::world::{CELL, TOWN_CELLS, island_input, island_path, nav_config};
use genex::nav::NavIsland;

fn assets_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("assets")
}

fn table(paths: &[String]) -> String {
    let rows: Vec<String> = paths.iter().map(|path| format!("    (\"{path}\", include_bytes!(\"../assets/{path}\")),")).collect();
    [
        "//! The town cells' offline nav islands, built into the binary. Generated by `tests/islands.rs`",
        "//! (`GENEX_FRONTIER_WRITE_ISLANDS=1`) from `world::island_input`; do not edit.",
        "",
        "/// Every island file: its path under `assets/` and its bytes.",
        "pub const ISLAND_FILES: &[(&str, &[u8])] = &[",
        &rows.join("\n"),
        "];",
        "",
    ]
    .join("\n")
}

#[test]
fn the_committed_islands_equal_a_fresh_offline_bake() {
    let write = std::env::var("GENEX_FRONTIER_WRITE_ISLANDS").is_ok_and(|v| v == "1");
    let config = nav_config();
    let mut paths = Vec::new();
    for cell in TOWN_CELLS {
        let island = NavIsland::bake_cell(&island_input(cell), &config, cell, CELL).expect("a town cell bakes");
        assert!(!island.tiles().is_empty(), "{cell:?} has walkable tiles");
        let bytes = island.to_bytes(&config);
        let path = island_path(cell);
        let file = assets_dir().join(&path);
        if write {
            std::fs::create_dir_all(file.parent().expect("a folder")).expect("the islands folder");
            std::fs::write(&file, &bytes).expect("the island writes");
        }
        let committed = std::fs::read(&file).unwrap_or_default();
        assert_eq!(committed, bytes, "{path}: the committed island is not this bake (re-bake with GENEX_FRONTIER_WRITE_ISLANDS=1)");
        let read = NavIsland::from_bytes(&committed).expect("the island reads");
        assert_eq!(read.tiles(), island.tiles(), "{path}: from_bytes gives the baked tiles");
        println!("{path}: {} tiles, {} bytes", island.tiles().len(), bytes.len());
        paths.push(path);
    }
    let table_file = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("src/island_table.rs");
    let text = table(&paths);
    if write {
        std::fs::write(&table_file, &text).expect("the table writes");
    }
    assert_eq!(std::fs::read_to_string(&table_file).unwrap_or_default(), text, "src/island_table.rs lists the islands");
}
