/**
 * Compiles stream-valley's placement file (`world/valley.cells.json`) with the host's own C-28
 * compiler, the one the import step runs on a game's `world/*.cells.json`, into the cell pack the
 * example ships (`assets/valley/world.json` and `assets/valley/cells/<x>_<z>.cell`) and the table
 * that compiles those files into the build (`src/pack_table.rs`). The packs are never written by
 * hand.
 *
 *   node native/genex-rust/examples/stream-valley/world/compile.ts           # write
 *   node native/genex-rust/examples/stream-valley/world/compile.ts --check   # exit 1 on a difference
 */
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { compileWorldCells, type WorldCellsFile } from "../../../../../src/substrate/asset-import/world-cells.ts";

const EXAMPLE = path.resolve(import.meta.dirname, "..");
const SOURCE = "world/valley.cells.json";
const ASSETS_DIR = path.join(EXAMPLE, "assets");
const TABLE = path.join(EXAMPLE, "src/pack_table.rs");
/** The models the example writes in code (`src/props.rs`), as an inventory would list them. */
const PROP_MODELS: ReadonlySet<string> = new Set([
  "models/hut.glb",
  "models/pine.glb",
  "models/rock.glb",
  "models/stone.glb",
  "models/tower.glb",
]);

function table(folder: string, files: readonly WorldCellsFile[]): string {
  const rows = files.map((file) => `    ("${file.path}", include_bytes!("../assets/${file.path}")),`);
  return [
    "//! The compiled cell pack, built into the binary. Generated by `world/compile.ts` from",
    "//! `world/valley.cells.json` (the host's C-28 compiler); do not edit.",
    "",
    "/// The pack's folder under `assets/`.",
    `pub const PACK_FOLDER: &str = "${folder}";`,
    "",
    "/// Every compiled file: its path under `assets/` and its bytes.",
    "pub const PACK_FILES: &[(&str, &[u8])] = &[",
    ...rows,
    "];",
    "",
  ].join("\n");
}

async function listed(dir: string): Promise<string[]> {
  const entries = await readdir(dir, { recursive: true, withFileTypes: true }).catch(() => []);
  return entries
    .filter((entry) => entry.isFile())
    .map((entry) => path.relative(ASSETS_DIR, path.join(entry.parentPath, entry.name)).split(path.sep).join("/"))
    .sort();
}

async function differences(folder: string, files: readonly WorldCellsFile[], text: string): Promise<string[]> {
  const out: string[] = [];
  const expected = new Set(files.map((file) => file.path));
  for (const rel of await listed(path.join(ASSETS_DIR, folder))) if (!expected.has(rel)) out.push(`extra ${rel}`);
  for (const file of files) {
    const bytes = await readFile(path.join(ASSETS_DIR, file.path)).catch(() => null);
    if (bytes === null || !Buffer.from(file.bytes).equals(bytes)) out.push(`differs ${file.path}`);
  }
  const committed = await readFile(TABLE, "utf8").catch(() => "");
  if (committed !== text) out.push("differs src/pack_table.rs");
  return out;
}

async function main(): Promise<number> {
  const check = process.argv.includes("--check");
  const source = await readFile(path.join(EXAMPLE, SOURCE));
  const result = await compileWorldCells(new Uint8Array(source), { source: SOURCE, assets: PROP_MODELS });
  if (!result.ok) {
    console.error(`stream-valley: ${SOURCE} refused ${result.refusal.code} at ${result.refusal.at}`);
    return 1;
  }
  const text = table(result.folder, result.files);
  if (check) {
    const found = await differences(result.folder, result.files, text);
    for (const line of found) console.error(`stream-valley: ${line}`);
    return found.length === 0 ? 0 : 1;
  }
  await rm(path.join(ASSETS_DIR, result.folder), { recursive: true, force: true });
  for (const file of result.files) {
    const target = path.join(ASSETS_DIR, file.path);
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, file.bytes);
  }
  await writeFile(TABLE, text);
  const { things, models, colliders, instances } = result.counts;
  console.log(
    `stream-valley: ${result.cells} cells, ${things} things, ${models} models, ${colliders} colliders, ${instances} instances`,
  );
  return 0;
}

process.exitCode = await main();
